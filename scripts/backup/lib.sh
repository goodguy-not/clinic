# Milestone 10, checkpoint A2 — shared by backup.sh, restore.sh, verify.sh and
# drill.sh. Sourced, never executed.
#
# Requires bash 4+, PostgreSQL 16+ client tools (pg_dump, pg_restore, psql) of
# at least the server's major version, GnuPG 2.2+, GNU tar and coreutils.

set -Eeuo pipefail
umask 077

BACKUP_LIB_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
BACKUP_SQL_DIR="$BACKUP_LIB_DIR/sql"
REPO_ROOT="$(cd "$BACKUP_LIB_DIR/../.." && pwd)"
BACKUP_FORMAT='clinic-backup/1'

# Row text — and therefore every table checksum — depends on these settings.
# Pinned for every psql and pg_dump this toolchain starts, so a backup taken on
# one server and verified on another compare like with like.
export PGTZ=UTC
export PGDATESTYLE='ISO, YMD'
export PGOPTIONS='-c IntervalStyle=postgres -c extra_float_digits=3 -c bytea_output=hex'
export PGCONNECT_TIMEOUT=15

say() { printf '%s\n' "$*"; }
step() { printf '\n==> %s\n' "$*"; }
ok() { printf '  OK   %s\n' "$*"; }

die() {
  printf '\n[%s] FAILED: %s\n' "${SCRIPT_NAME:-backup}" "$*" >&2
  exit 1
}

require_env() {
  local name
  for name in "$@"; do
    [[ -n "${!name:-}" ]] || die "$name is required (README, Backup and restore)."
  done
}

require_cmd() {
  local name
  for name in "$@"; do
    command -v "$name" > /dev/null 2>&1 || die "required command not found: $name"
  done
}

# psql as this toolchain always runs it: no ~/.psqlrc, stop at the first error.
psql_run() {
  psql -X -q -v ON_ERROR_STOP=1 "$@"
}

# A single value from a single query.
psql_value() {
  local url="$1" sql="$2"
  psql_run -A -t -d "$url" -c "$sql"
}

# The server major version a URL points at, and a refusal if the local client
# tools are older: pg_dump cannot read a newer server, and pg_restore of a
# newer archive fails halfway.
check_client_version() {
  local url="$1" server client
  server="$(psql_value "$url" "SELECT current_setting('server_version_num')::int / 10000")"
  client="$(pg_dump --version | sed -E 's/^[^0-9]*([0-9]+).*/\1/')"
  if ((client < server)); then
    die "pg_dump $client is older than the PostgreSQL $server server. Install the $server client tools."
  fi
  if ((client < 16)); then
    die "PostgreSQL client tools 16 or later are required (found $client)."
  fi
}

# A storage key is generated by MediaStorageService.keyFor: two fan-out levels,
# the asset id, a generated file name. Anything else is refused before it
# reaches a path — a key that arrived by a hand-written UPDATE or a forged
# archive must not be able to name a file outside the media root.
assert_media_keys_safe() {
  local list="$1" bad
  bad="$(awk '{print $2}' "$list" \
    | grep -Ev '^[0-9a-f]{2}/[0-9a-f]{2}/[0-9a-f-]{36}/[a-z0-9]+\.[a-z0-9]+$' || true)"
  if [[ -n "$bad" ]]; then
    die "refusing unexpected media storage key(s): $(head -5 <<< "$bad" | tr '\n' ' ')"
  fi
}

# Every file a list names exists under a root and has the listed SHA-256.
# Missing and altered files are both named, then refused.
check_media_against() {
  local root="$1" list="$2" label="$3" report
  local total
  total="$(wc -l < "$list" | tr -d ' ')"
  if ((total == 0)); then
    ok "$label: no stored media referenced"
    return 0
  fi
  if ! report="$(cd "$root" && sha256sum --check --strict --quiet "$list" 2>&1)"; then
    printf '%s\n' "$report" | head -20 >&2
    die "$label: $(grep -c 'FAILED' <<< "$report") of $total referenced media file(s) missing or altered (first 20 above)."
  fi
  ok "$label: all $total referenced media file(s) present, SHA-256 matches"
}

# Everything the manifest recorded, recomputed against a database and compared.
# The media list is recomputed from the database's own rows, so a restore that
# lost or altered a row is caught here and not only by the file check.
compare_manifest() {
  local url="$1" stage="$2" out="$3"
  assert_no_space "$out"
  mkdir -p "$out"
  psql_run -d "$url" \
    -v tables_file="$out/tables.txt" \
    -v sequences_file="$out/sequences.txt" \
    -v schema_file="$out/schema.txt" \
    -v media_file="$out/media.sha256" \
    -f "$BACKUP_SQL_DIR/manifest.sql"

  local name
  for name in tables.txt sequences.txt schema.txt media.sha256; do
    if ! diff -u "$stage/manifest/$name" "$out/$name" > "$out/$name.diff"; then
      head -40 "$out/$name.diff" >&2
      die "restored $name differs from the backup's manifest (first 40 diff lines above)."
    fi
  done

  local tables rows
  tables="$(wc -l < "$out/tables.txt" | tr -d ' ')"
  rows="$(awk -F'|' '{s += $2} END {print s + 0}' "$out/tables.txt")"
  ok "tables: $tables tables, $rows rows — every count and checksum matches the backup"
  ok "sequences: $(wc -l < "$out/sequences.txt" | tr -d ' ') match"
  ok "media rows: $(wc -l < "$out/media.sha256" | tr -d ' ') referenced files, same keys and hashes as the backup"
  local facts="$out/schema.txt"
  ok "schema: $(grep -c '^trigger|' "$facts") triggers (with enabled state), $(grep -c '^constraint|' "$facts") constraints, $(grep -c '^index|' "$facts") indexes, $(grep -c '^function|' "$facts") functions, $(grep -c '^grant|' "$facts") grants — identical to the backup"
}

# psql's \o takes a bare file name, so the working directories cannot have one
# with a space in it.
assert_no_space() {
  [[ "$1" != *[[:space:]]* ]] || die "working directory $1 contains whitespace; set BACKUP_WORK_DIR / RESTORE_WORK_DIR."
}

meta_value() {
  awk -F'|' -v key="$2" '$1 == key {print $2}' "$1/manifest/meta.txt"
}

# Decrypts and unpacks an archive into a staging directory. Nothing outside the
# staging directory is touched, so a wrong key, a truncated file or a tampered
# archive fails here, before any database or media directory is changed.
unpack_archive() {
  local archive="$1" stage="$2"
  [[ -f "$archive" ]] || die "no such archive: $archive"
  mkdir -p "$stage/content"
  if ! gpg --batch --quiet --decrypt "$archive" 2> "$stage/gpg.err" \
    | tar -C "$stage/content" --no-same-owner -xf - 2> "$stage/tar.err"; then
    cat "$stage/gpg.err" "$stage/tar.err" >&2
    die "could not decrypt and unpack $archive: wrong or missing private key, or a damaged or altered archive. Nothing was restored."
  fi
  [[ "$(cat "$stage/content/FORMAT" 2> /dev/null)" == "$BACKUP_FORMAT" ]] \
    || die "$archive is not a $BACKUP_FORMAT archive."
  local file
  for file in manifest/meta.txt manifest/tables.txt manifest/sequences.txt \
    manifest/schema.txt manifest/media.sha256 database.dump; do
    [[ -f "$stage/content/$file" ]] || die "$archive is incomplete: $file is missing."
  done
  mkdir -p "$stage/content/media"
  assert_media_keys_safe "$stage/content/manifest/media.sha256"
}
