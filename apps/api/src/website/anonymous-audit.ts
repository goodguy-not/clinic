import type { AuditContext } from '../audit/audit.types';
import type { RequestContext } from '../common/request-context';

/**
 * The audit context for the one act in this application performed by nobody.
 *
 * Milestone 9, checkpoint A3.
 *
 * EVERY OTHER AUDITED WRITE IN THIS APPLICATION RECORDS THE CALLER'S IP ADDRESS
 * AND USER AGENT. `AuditService.record` writes `context.clientIp` and
 * `context.userAgent` into `audit_log` from whatever context it is handed, and
 * `actorContext` in `catalog/catalog-support.ts` — the builder every staff write
 * path uses — passes both straight through. That is right for a member of staff:
 * they are a known, consenting employee performing an act on clinic records, and
 * "which machine was this done from?" is a forensic question the clinic is
 * entitled to be able to answer about its own people.
 *
 * IT IS NOT RIGHT FOR AN ANONYMOUS VISITOR, AND THIS FUNCTION IS THE DIFFERENCE.
 * A stranger's IP address and browser string are personal data about somebody
 * who has no employment relationship with the clinic, gathered under a notice
 * that promises their submission will not be kept beyond ninety days.
 * `audit_log` is append-only and unprunable — that is its whole value — so an IP
 * written there would be a PERMANENT record of a person the clinic has promised
 * to forget, sitting in the one table the ninety-day erasure cannot reach. The
 * promise would be false the moment it was made.
 *
 * THIS IS THE ACCEPTED A3 AUDIT FALLBACK, AND IT IS THE NARROW END OF IT. The
 * shared machinery CAN truthfully produce the required record — `AuditContext`
 * makes `clientIp` and `userAgent` optional, so passing them as `null` writes
 * SQL NULLs into both columns rather than smuggling values through. What the
 * machinery cannot do on its own is guarantee that a future call site remembers
 * to. So the guarantee lives here: this is the ONLY builder in the application
 * that constructs an `ANONYMOUS` audit context, it takes a `RequestContext`
 * that HAS both values and drops them where a reader can see it happen, and an
 * integration test reads the two columns back out of PostgreSQL and asserts they
 * are NULL. A second, bespoke audit table for anonymous acts was the alternative,
 * and it was rejected: two audit trails is one more than a reviewer can be
 * expected to know about.
 *
 * ABUSE CONTROL DOES NOT NEED THE AUDIT TRAIL AND MUST NOT USE IT. The
 * fingerprint that bounds a flooder is a keyed hash in a purgeable column of the
 * request row (`request-fingerprint.ts`), where it is cleared with the rest of
 * the content — or earlier, on its own. Operational
 * visibility into refusals is `security-log.ts`, which is rotatable and prunable
 * and is where every non-state-changing rejection in this application already
 * goes.
 *
 * WHAT IS LEFT IS THE REQUEST ID, AND THAT IS DELIBERATE. It is generated by
 * this application, it names no person, and it is what ties the audit row to the
 * server log line and to the error envelope a visitor may quote — the property
 * every other audited act in the product has, kept here at no privacy cost.
 */
export function anonymousWebsiteAuditContext(context: RequestContext): AuditContext {
  return {
    actor: { type: 'ANONYMOUS' },
    requestId: context.requestId,
    // Dropped, not forwarded. See above. Written out as explicit nulls rather
    // than omitted, so that the decision is visible in the object a reader is
    // looking at instead of being an absence they have to notice.
    clientIp: null,
    userAgent: null,
  };
}
