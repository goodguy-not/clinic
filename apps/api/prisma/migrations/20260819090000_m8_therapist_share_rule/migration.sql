-- ===========================================================================
-- HAND-WRITTEN: constraints and triggers Prisma cannot express.
--
-- NOTE ON THE FOREIGN KEYS ABOVE. All four are ON DELETE RESTRICT, and both
-- user keys are NOT NULL where the act happened: a rule is entered by a
-- signed-in manager and a void is performed by one, and the row names them.
-- `voided_by_user_id` is nullable only because a live rule has not been voided;
-- the CHECK below ties it to `voided_at` so a voided row always names its actor.
--
-- The self-referencing `supersedes_share_rule_id` is RESTRICT for the reason
-- every historical reference in this schema is: a superseded rule is history,
-- and history keeps its references.
-- ===========================================================================

-- --- share percentage bounds -------------------------------------------------
--
-- BASIS POINTS, 0 TO 10000 INCLUSIVE — hundredths of one percent, so 40 percent
-- is 4000. An INTEGER column and a bound in the database, not only in Zod:
-- a percentage is the multiplier on somebody's earnings, and the one place it
-- must be impossible to store 105 percent or a negative share is the place a
-- migration script or a psql prompt writes to.
--
-- Both ends are legitimate values rather than sentinels. 0 is a therapist who
-- takes no share of this work — salaried cover, a clinic-funded programme — and
-- 10000 is an arrangement where the whole session value is theirs. Neither
-- means "unconfigured": that state is the ABSENCE of a covering row.
ALTER TABLE "therapist_share_rule" ADD CONSTRAINT "therapist_share_rule_basis_points_chk"
    CHECK ("share_basis_points" >= 0 AND "share_basis_points" <= 10000);

-- --- effective range ---------------------------------------------------------
--
-- A NULL end is open-ended, which is the common case for a current agreement.
ALTER TABLE "therapist_share_rule" ADD CONSTRAINT "therapist_share_rule_effective_range_chk"
    CHECK ("effective_end" IS NULL OR "effective_end" >= "effective_start");

-- --- void consistency --------------------------------------------------------
--
-- A voided rule always records WHEN, BY WHOM and WHY, and a live one never
-- claims any of the three. One CHECK over all three columns rather than three
-- separate ones, because the invariant is that they move together: a row with a
-- void reason and no actor would be a withdrawal nobody performed.
ALTER TABLE "therapist_share_rule" ADD CONSTRAINT "therapist_share_rule_void_consistency_chk"
    CHECK (
        ("voided_at" IS NULL) = ("void_reason" IS NULL)
        AND ("voided_at" IS NULL) = ("voided_by_user_id" IS NULL)
    );

ALTER TABLE "therapist_share_rule" ADD CONSTRAINT "therapist_share_rule_void_reason_chk"
    CHECK (
        "void_reason" IS NULL
        OR (
            "void_reason" = btrim("void_reason")
            AND btrim("void_reason") <> ''
            AND length("void_reason") <= 500
        )
    );

-- --- a rule never supersedes itself -----------------------------------------
--
-- The foreign key permits it — a row may reference its own id — and a rule that
-- superseded itself would be a correction of nothing that reads as a correction
-- of something.
ALTER TABLE "therapist_share_rule" ADD CONSTRAINT "therapist_share_rule_self_supersede_chk"
    CHECK ("supersedes_share_rule_id" IS NULL OR "supersedes_share_rule_id" <> "id");

-- --- overlap prevention ------------------------------------------------------
--
-- AT MOST ONE LIVE RULE MAY COVER A THERAPIST ON ANY GIVEN DAY. This is the
-- constraint the whole checkpoint rests on: resolution asks "which percentage
-- applied to this therapist on this service date?", and a question about
-- somebody's earnings must have exactly one answer or none — never two, and
-- never one arbitrarily chosen from two.
--
-- ONE CONSTRAINT, NOT TWO. `tariff` needs a pair because its therapist scope is
-- nullable and `=` in an exclusion constraint does not treat NULL as equal to
-- NULL. Here `therapist_id` is NOT NULL, so a single constraint covers every
-- row, and there is no general-scope case to leave silently unguarded.
--
-- Partial on `voided_at IS NULL`: a voided rule is history and may overlap
-- anything, which is precisely what makes a correction expressible — the
-- replacement covers a range the withdrawn row still covers.
--
-- ENFORCED HERE RATHER THAN BY READING BEFORE WRITING, because that is the
-- difference between an invariant and a convention. Two managers submitting
-- overlapping ranges at the same instant both find the range free if the
-- application checks first; against this constraint exactly one of them commits
-- and the other is refused, whatever either read.
--
-- `btree_gist` is already installed by the Milestone 2 migration, which needed
-- it for the same reason: a GiST index cannot compare uuid values with `=`
-- without it.
ALTER TABLE "therapist_share_rule" ADD CONSTRAINT "therapist_share_rule_no_overlap_excl"
    EXCLUDE USING GIST (
        "therapist_id" WITH =,
        daterange("effective_start", "effective_end", '[]') WITH &&
    ) WHERE ("voided_at" IS NULL);

-- --- no-delete enforcement (reuses the Milestone 1 shared function) ----------
--
-- A share rule is a permanent historical record: it will be named by a rated
-- session's snapshot, and "what was this therapist's percentage in Tir?" must
-- keep its answer forever. Withdrawal is `voided_at`, never a DELETE.
--
-- The TRUNCATE trigger is not optional — TRUNCATE bypasses row-level triggers
-- entirely.
CREATE TRIGGER "therapist_share_rule_no_delete"
    BEFORE DELETE ON "therapist_share_rule"
    FOR EACH ROW EXECUTE FUNCTION "raise_append_only_violation"();

CREATE TRIGGER "therapist_share_rule_no_truncate"
    BEFORE TRUNCATE ON "therapist_share_rule"
    FOR EACH STATEMENT EXECUTE FUNCTION "raise_append_only_violation"();

-- --- immutability ------------------------------------------------------------
--
-- A share rule is written once. Correcting a percentage voids the row and
-- inserts a replacement, so the percentage that applied on a past date stays
-- readable exactly as it was applied — and a later change to the agreement
-- cannot, by itself, rewrite a historical session's settlement.
--
-- Enforced here rather than only in the service layer for the reason
-- `enforce_tariff_immutability` is: a future endpoint, a migration script or a
-- debugging session at a psql prompt must not be able to rewrite what a
-- therapist was agreed to earn.
--
-- Exactly one transition is permitted: live to voided. Everything else —
-- changing the percentage, moving the effective range, re-pointing the rule at
-- another therapist, unvoiding, or rewriting a void reason after the fact —
-- raises restrict_violation (SQLSTATE 23001), the same stable code every "the
-- database refuses to rewrite this" guard in this project uses.
CREATE OR REPLACE FUNCTION "enforce_therapist_share_rule_immutability"() RETURNS trigger
    LANGUAGE plpgsql AS $fn$
BEGIN
    -- Whose agreement it is, what it pays, and when it applied. None of it
    -- changes, ever — voided or not. `share_basis_points` and the effective
    -- range are as defining as each other: moving a range silently reassigns
    -- which sessions a percentage governs, which is the same edit as changing
    -- the percentage.
    IF NEW."id"                       IS DISTINCT FROM OLD."id"
        OR NEW."therapist_id"             IS DISTINCT FROM OLD."therapist_id"
        OR NEW."share_basis_points"       IS DISTINCT FROM OLD."share_basis_points"
        OR NEW."effective_start"          IS DISTINCT FROM OLD."effective_start"
        OR NEW."effective_end"            IS DISTINCT FROM OLD."effective_end"
        OR NEW."supersedes_share_rule_id" IS DISTINCT FROM OLD."supersedes_share_rule_id"
        OR NEW."created_at"               IS DISTINCT FROM OLD."created_at"
        OR NEW."created_by_user_id"       IS DISTINCT FROM OLD."created_by_user_id"
    THEN
        RAISE EXCEPTION
            'therapist share rule % is immutable; only a single void transition is permitted',
            OLD."id"
            USING ERRCODE = 'restrict_violation';
    END IF;

    -- Voiding is a one-way door. Once voided, the void itself is history too:
    -- no unvoiding, and no revising the stated reason or the recorded actor
    -- afterwards.
    IF OLD."voided_at" IS NOT NULL
        AND (
            NEW."voided_at"         IS DISTINCT FROM OLD."voided_at"
            OR NEW."void_reason"       IS DISTINCT FROM OLD."void_reason"
            OR NEW."voided_by_user_id" IS DISTINCT FROM OLD."voided_by_user_id"
        )
    THEN
        RAISE EXCEPTION
            'therapist share rule % is already voided; the void cannot change again', OLD."id"
            USING ERRCODE = 'restrict_violation';
    END IF;

    RETURN NEW;
END;
$fn$;

CREATE TRIGGER "therapist_share_rule_enforce_immutability"
    BEFORE UPDATE ON "therapist_share_rule"
    FOR EACH ROW EXECUTE FUNCTION "enforce_therapist_share_rule_immutability"();

