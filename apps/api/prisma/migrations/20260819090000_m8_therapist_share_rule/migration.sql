-- Milestone 8, checkpoint C2 — the therapist share rule.
--
-- ONE TABLE, AND IT IS CONFIGURATION RATHER THAN A SETTLEMENT FACT. It records
-- the agreement — what percentage of a session's value this therapist takes,
-- between which dates — and says nothing about any session. What a session
-- earned is a per-session snapshot copied off a rule at the moment the session
-- is rated, and that table is checkpoint C3's, not this one's.
--
-- WHAT IS DELIBERATELY NOT HERE, and none of it is an oversight:
--
--   * NO `session_settlement`, NO `settlement_period`, NO `settlement_line`.
--     Those are later checkpoints. `catalog-schema.int-spec.ts` lists every
--     table in the database, so one arriving early fails a test.
--   * NO COLUMN ON `session_charge` OF ANY KIND. Rating a session is C3, and
--     the charge is untouched here.
--   * NO SERVICE, DURATION OR FAMILY SCOPE ON THE RULE. CLAUDE.md approves
--     percentages that differ BY THERAPIST and change OVER TIME, and nothing
--     else; a second scope dimension would be a settlement rule inferred
--     rather than approved. It stays additive if it is ever approved.
--   * NO DEFAULT SHARE, and therefore no DEFAULT on `share_basis_points`. A
--     therapist with no rule covering a date has NO share, which the service
--     reports as `SHARE_RULE_MISSING`. Zero is a legitimate agreed share, so a
--     default of zero would make "not configured" indistinguishable from
--     "agreed to take nothing".
--   * NO PAYOUT, NO LEDGER POSITION, NO BALANCE. This milestone records no
--     money leaving the clinic.
--
-- The section above the "HAND-WRITTEN" banner is generated by Prisma.
-- Everything below it is reviewed by a human, because Prisma cannot express
-- CHECK constraints, exclusion constraints or triggers. Each hand-written
-- object is named, and `settlement-share-rules.int-spec.ts` asserts every name
-- exists in the PostgreSQL catalogue, so a future edit cannot quietly drop one.
--
-- THIS MIGRATION IS CREATE-ONLY. It adds one table, its indexes and the objects
-- below; it alters no existing column, adds no enum and drops nothing, so it
-- cannot fail on existing data and there is nothing to back-fill.
--
-- ON TIMESTAMPS: as in every earlier migration, `CURRENT_TIMESTAMP` is
-- PostgreSQL's exact synonym for `transaction_timestamp()`, left spelled as
-- Prisma generates it so drift detection cannot produce a false positive on a
-- synonym. `effective_start` and `effective_end` are not clock readings at all:
-- they are calendar days, as `tariff.effective_start` is, so the day an
-- agreement began never depends on the reader's timezone.

-- CreateTable
CREATE TABLE "therapist_share_rule" (
    "id" UUID NOT NULL,
    "therapist_id" UUID NOT NULL,
    "share_basis_points" INTEGER NOT NULL,
    "effective_start" DATE NOT NULL,
    "effective_end" DATE,
    "supersedes_share_rule_id" UUID,
    "created_at" TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "created_by_user_id" UUID NOT NULL,
    "voided_at" TIMESTAMPTZ,
    "voided_by_user_id" UUID,
    "void_reason" TEXT,

    CONSTRAINT "therapist_share_rule_pkey" PRIMARY KEY ("id")
);

