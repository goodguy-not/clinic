-- Milestone 9.5, checkpoint A5 — coordinator revision. TWO CORRECTIONS, NO NEW
-- TABLE, AND NO NEW POLICY.
--
-- 1. FRAMING, ON THE ATTACHMENT.
--
-- The first checkpoint stored a photograph and derived five widths of it, and
-- had no answer at all to "her face is off to the left in the round avatar".
-- Six columns on `media_attachment` are that answer, and every one of them is a
-- DESCRIPTION rather than an instruction to the encoder.
--
-- NOTHING HERE TOUCHES A PIXEL. The stored renditions remain the WHOLE FRAME;
-- these numbers tell a renderer which part of that frame matters. Three product
-- requirements fall straight out of that one decision:
--
--   * framing changes WITHOUT RE-UPLOADING the source — it is one UPDATE;
--   * re-framing CANNOT DESTROY OR REWRITE THE MASTER, because a crop is a
--     description and is therefore reversible for ever. A crop encoded into the
--     stored bytes would throw away everything outside it, and the only way
--     back would be to ask a family for the photograph again;
--   * the web tier can PREVIEW A CROP LIVE, because applying a normalised
--     rectangle and a focal point is CSS rather than a request.
--
-- ON THE ATTACHMENT AND NOT ON THE ASSET, deliberately. One photograph of the
-- therapy room may be a wide banner on one page and a square tile on another;
-- those are two attachments with two framings over one master. Framing on the
-- asset would make the second use silently re-frame the first.
--
-- FRACTIONS OF THE FRAME, NEVER PIXELS. A pixel rectangle means something
-- different on each of the five rendition widths, so a crop chosen against one
-- would be wrong on the rest. The focal point defaults to the centre, which is
-- exactly what a browser does to an unframed image, so every attachment that
-- already exists keeps behaving as it did.
--
-- 2. ERASURE, MADE REPRESENTABLE — AND STILL NOT IMPLEMENTED.
--
-- The first checkpoint said "nothing deletes a byte" and left `storage_key` NOT
-- NULL, which quietly made the OPPOSITE decision from the one the owner has
-- open: it made "these bytes are gone" a state the schema could not express, so
-- the retention policy, whenever it is taken, would have had to arrive as a
-- migration that drops NOT NULL on a live table full of a clinic's
-- photographs.
--
-- So the two storage keys become nullable and each gains a purge marker, tied
-- together in both directions by a CHECK. NOTHING IN THIS APPLICATION WRITES
-- EITHER MARKER. There is no schedule, no duration, no route, no permission and
-- no CLI command for erasure anywhere in Milestone 9.5, because the retention
-- policy is an owner decision nobody has taken — and inventing one here is
-- exactly what the frozen boundary forbids.
--
-- WHAT THIS BUYS IS THAT THE DECISION STAYS CHEAP. Once it is taken, an erasure
-- is an UPDATE that sets the marker and clears the key, plus an unlink of the
-- files: no new table, no model change, no rewriting of what is stored. It is
-- the `website_request.purged_at` pattern applied to bytes — the row that
-- remains says a photograph existed and where it was used, and the content it
-- described is gone.
--
-- THE `no_delete` TRIGGERS STAY, AND THEY ARE NOT A CONTRADICTION. They refuse
-- routine, unaudited, whole-row destruction, which is what every historical
-- table in this schema refuses. A future retention checkpoint that decides rows
-- as well as bytes must go must lift them explicitly, in a reviewed migration,
-- for named tables — which is a deliberate act with a policy behind it rather
-- than something a stray statement can do. `media-retention-readiness.int-spec.ts`
-- proves that path works today, in dependency order, with no foreign key or
-- model obstacle in the way.
--
-- The section above the "HAND-WRITTEN" banner is generated by Prisma.
-- Everything below it is reviewed by a human, named, and pinned by
-- `media-schema.int-spec.ts`.

-- AlterTable
ALTER TABLE "media_asset" ADD COLUMN     "bytes_purged_at" TIMESTAMPTZ,
ALTER COLUMN "master_storage_key" DROP NOT NULL;

-- AlterTable
ALTER TABLE "media_attachment" ADD COLUMN     "crop_height" DOUBLE PRECISION,
ADD COLUMN     "crop_width" DOUBLE PRECISION,
ADD COLUMN     "crop_x" DOUBLE PRECISION,
ADD COLUMN     "crop_y" DOUBLE PRECISION,
ADD COLUMN     "focal_x" DOUBLE PRECISION NOT NULL DEFAULT 0.5,
ADD COLUMN     "focal_y" DOUBLE PRECISION NOT NULL DEFAULT 0.5;

-- AlterTable
ALTER TABLE "media_rendition" ADD COLUMN     "bytes_purged_at" TIMESTAMPTZ,
ALTER COLUMN "storage_key" DROP NOT NULL;

-- ===========================================================================
-- HAND-WRITTEN: everything below this line is reviewed, not generated.
-- ===========================================================================

-- --- framing -----------------------------------------------------------------
--
-- The focal point is a point inside the frame. Bounded rather than merely
-- numeric, because a renderer given 47 for a fraction produces a layout nobody
-- can explain, and the failure would appear only on the one page that crops.

ALTER TABLE "media_attachment" ADD CONSTRAINT "media_attachment_focal_chk"
    CHECK (
        "focal_x" >= 0 AND "focal_x" <= 1
        AND "focal_y" >= 0 AND "focal_y" <= 1
    );

-- THE CROP IS FOUR COLUMNS AND ONE FACT, so all four arrive together or none
-- does. A rectangle with a width and no origin is not a partially specified
-- crop, it is a bug that would render as a full-frame image on one page and a
-- sliver on another.
--
-- IT MUST LIE INSIDE THE FRAME. Width and height are strictly positive — a
-- zero-area crop is an invisible image, which is never what somebody dragging a
-- handle meant — and the far edge may not pass 1.
ALTER TABLE "media_attachment" ADD CONSTRAINT "media_attachment_crop_chk"
    CHECK (
        (
            "crop_x" IS NULL
            AND "crop_y" IS NULL
            AND "crop_width" IS NULL
            AND "crop_height" IS NULL
        )
        OR (
            "crop_x" IS NOT NULL
            AND "crop_y" IS NOT NULL
            AND "crop_width" IS NOT NULL
            AND "crop_height" IS NOT NULL
            AND "crop_x" >= 0
            AND "crop_y" >= 0
            AND "crop_width" > 0
            AND "crop_height" > 0
            AND "crop_x" + "crop_width" <= 1
            AND "crop_y" + "crop_height" <= 1
        )
    );

-- --- erasure, in both directions ---------------------------------------------
--
-- The key is present exactly while the bytes are. Stating it as an equality
-- rather than as two one-way implications is what makes both mistakes
-- impossible: a row that claims to have been erased while still naming a file,
-- and a row that has lost its file with nothing to say why.

ALTER TABLE "media_asset" ADD CONSTRAINT "media_asset_purge_chk"
    CHECK (("master_storage_key" IS NULL) = ("bytes_purged_at" IS NOT NULL));

ALTER TABLE "media_rendition" ADD CONSTRAINT "media_rendition_purge_chk"
    CHECK (("storage_key" IS NULL) = ("bytes_purged_at" IS NOT NULL));
