-- --- sessions: prunable, but only once long over -----------------------------
--
-- A session is OVER at the earliest of its absolute expiry, its idle expiry and
-- its revocation. Thirty days after that it is removed: long enough to answer
-- "was this session still live when X happened?" during an incident, and the
-- acts it performed are in `audit_log` for ever, which names the session by a
-- plain UUID with no foreign key.
--
-- THE WINDOW IS STATED HERE AS WELL AS IN THE SERVICE, deliberately — the
-- `website_request_purge_eligibility_chk` pattern. Shortening it in code alone
-- is a refusal, not an early deletion. A live session cannot be deleted by the
-- runtime at all: it is REVOKED, which is audited.

CREATE OR REPLACE FUNCTION "user_session_prune_only_ended"() RETURNS trigger
    LANGUAGE plpgsql
    SET search_path = pg_catalog, public
AS $$
BEGIN
    IF LEAST(
           OLD."absolute_expires_at",
           OLD."idle_expires_at",
           COALESCE(OLD."revoked_at", 'infinity'::timestamptz)
       ) > transaction_timestamp() - interval '30 days' THEN
        RAISE EXCEPTION 'user_session % has not been over for thirty days and may not be removed', OLD."id"
            USING ERRCODE = '23001';
    END IF;

    RETURN OLD;
END;
$$;

CREATE TRIGGER "user_session_prune_only_ended"
    BEFORE DELETE ON "user_session"
    FOR EACH ROW EXECUTE FUNCTION "user_session_prune_only_ended"();

GRANT DELETE ON "user_session" TO clinic_runtime;

-- --- media: when a photograph's bytes may be erased --------------------------
--
-- THE OWNER'S THREE RULES, ONCE, IN SQL. A photograph is due for erasure when
--
--   * it was uploaded at least thirty days ago and has NEVER been attached
--     anywhere — no `media_attachment` row has ever named it, and since those
--     rows are never deleted, "no row" is exactly "never attached";
--   * a manager archived it at least thirty days ago (restoring it within the
--     thirty days clears `archived_at`, and the clock with it); or
--   * it has ever been attached to a testimonial whose family has withdrawn
--     consent — however long ago, and whether or not it was later detached,
--     because it is the family's photograph either way.
--
-- The job finds its work with its own predicate (`media-erasure.service.ts`);
-- this is what makes a mistake in that predicate a loud refusal rather than a
-- quiet destruction. Neither is redundant — the website-request precedent.

CREATE OR REPLACE FUNCTION "media_asset_erasure_is_due"("asset_id" uuid) RETURNS boolean
    LANGUAGE sql
    STABLE
    SET search_path = pg_catalog, public
AS $$
    SELECT EXISTS (
        SELECT 1 FROM "media_asset" a
        WHERE a."id" = "asset_id"
          AND (
              (
                  a."status" = 'ARCHIVED'
                  AND a."archived_at" <= transaction_timestamp() - interval '30 days'
              )
              OR (
                  a."created_at" <= transaction_timestamp() - interval '30 days'
                  AND NOT EXISTS (
                      SELECT 1 FROM "media_attachment" m WHERE m."media_asset_id" = a."id"
                  )
              )
              OR EXISTS (
                  SELECT 1
                  FROM "media_attachment" m
                  JOIN "public_testimonial" t ON t."id" = m."testimonial_id"
                  WHERE m."media_asset_id" = a."id"
                    AND t."consent_withdrawn_at" IS NOT NULL
              )
          )
    );
$$;

-- THE ASSET. Erasure is one transition — the master key cleared and
-- `bytes_purged_at` stamped, nothing else changed — and only when due. Once
-- erased it is final: the key cannot come back, the marker cannot move, and an
-- archived photograph whose bytes are gone cannot be restored into circulation.
-- Everything else about an erased asset (its description, its archiving) stays
-- editable, as before.

CREATE OR REPLACE FUNCTION "media_asset_erasure_guard"() RETURNS trigger
    LANGUAGE plpgsql
    SET search_path = pg_catalog, public
AS $$
BEGIN
    IF OLD."bytes_purged_at" IS NULL AND NEW."bytes_purged_at" IS NOT NULL THEN
        IF (to_jsonb(NEW) - 'master_storage_key' - 'bytes_purged_at')
           IS DISTINCT FROM (to_jsonb(OLD) - 'master_storage_key' - 'bytes_purged_at') THEN
            RAISE EXCEPTION 'media_asset % erasure may change nothing but its bytes', OLD."id"
                USING ERRCODE = '23001';
        END IF;

        IF NOT "media_asset_erasure_is_due"(OLD."id") THEN
            RAISE EXCEPTION 'media_asset % is not due for erasure', OLD."id"
                USING ERRCODE = '23001';
        END IF;
    ELSIF OLD."bytes_purged_at" IS NOT NULL THEN
        IF NEW."bytes_purged_at" IS DISTINCT FROM OLD."bytes_purged_at"
           OR NEW."master_storage_key" IS DISTINCT FROM OLD."master_storage_key" THEN
            RAISE EXCEPTION 'media_asset % has been erased, and erasure is final', OLD."id"
                USING ERRCODE = '23001';
        END IF;

        IF OLD."status" = 'ARCHIVED' AND NEW."status" = 'ACTIVE' THEN
            RAISE EXCEPTION 'media_asset % has been erased and cannot be restored', OLD."id"
                USING ERRCODE = '23001';
        END IF;
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER "media_asset_erasure_guard"
    BEFORE UPDATE ON "media_asset"
    FOR EACH ROW EXECUTE FUNCTION "media_asset_erasure_guard"();

-- THE RENDITION. Append-only until now, and still append-only in every respect
-- but one: the erasure of a rendition whose photograph is due. That is the only
-- UPDATE this trigger lets through, for the runtime and for the owner alike.

CREATE OR REPLACE FUNCTION "media_rendition_erasure_only"() RETURNS trigger
    LANGUAGE plpgsql
    SET search_path = pg_catalog, public
AS $$
BEGIN
    IF OLD."bytes_purged_at" IS NOT NULL
       OR NEW."bytes_purged_at" IS NULL
       OR NEW."storage_key" IS NOT NULL
       OR (to_jsonb(NEW) - 'storage_key' - 'bytes_purged_at')
          IS DISTINCT FROM (to_jsonb(OLD) - 'storage_key' - 'bytes_purged_at') THEN
        RAISE EXCEPTION 'media_rendition % is append-only; the only permitted change is its erasure', OLD."id"
            USING ERRCODE = '23001';
    END IF;

    IF NOT "media_asset_erasure_is_due"(OLD."media_asset_id") THEN
        RAISE EXCEPTION 'media_rendition % belongs to a photograph that is not due for erasure', OLD."id"
            USING ERRCODE = '23001';
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER "media_rendition_erasure_only"
    BEFORE UPDATE ON "media_rendition"
    FOR EACH ROW EXECUTE FUNCTION "media_rendition_erasure_only"();

