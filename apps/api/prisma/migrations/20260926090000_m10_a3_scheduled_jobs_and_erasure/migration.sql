-- --- testimonials: consent withdrawn, then the content erased -----------------
--
-- A WITHDRAWN TESTIMONIAL IS NEVER ON THE SITE AND NEVER APPROVED. Recording the
-- withdrawal revokes both in the same statement, and this constraint is why
-- nothing can put them back.

ALTER TABLE "public_testimonial" ADD CONSTRAINT "public_testimonial_withdrawal_chk"
    CHECK (
        ("consent_withdrawn_at" IS NULL) = ("consent_withdrawn_by_user_id" IS NULL)
        AND (
            "consent_withdrawn_at" IS NULL
            OR ("status" = 'DRAFT' AND "is_public" IS FALSE)
        )
    );

-- ERASED EXACTLY WHEN THE WORDS ARE GONE, AND ONLY AFTER A WITHDRAWAL. `body` is
-- NULL if and only if `content_erased_at` is set, the attribution goes with it,
-- and nothing but a withdrawal makes a testimonial erasable: a manager who
-- merely wants a quotation off the site unpublishes it.

ALTER TABLE "public_testimonial" ADD CONSTRAINT "public_testimonial_erasure_chk"
    CHECK (
        ("body" IS NULL) = ("content_erased_at" IS NOT NULL)
        AND ("content_erased_at" IS NULL OR "consent_withdrawn_at" IS NOT NULL)
        AND ("content_erased_at" IS NULL OR "author_label" IS NULL)
    );

-- The Milestone 9.5 A7 handwriting rule, restated with its one exception: an
-- erased testimonial has no transcription because it has nothing at all.
ALTER TABLE "public_testimonial" DROP CONSTRAINT "public_testimonial_handwritten_body_chk";

ALTER TABLE "public_testimonial" ADD CONSTRAINT "public_testimonial_handwritten_body_chk"
    CHECK (
        "kind" <> 'HANDWRITTEN'
        OR "content_erased_at" IS NOT NULL
        OR ("body" IS NOT NULL AND btrim("body") <> '')
    );

-- BOTH ACTS ARE FINAL. After a withdrawal the only change the row accepts is the
-- erasure — words and attribution cleared, the marker stamped, nothing else
-- touched — and after the erasure it accepts none. A withdrawal cannot be
-- undone, re-dated or re-attributed.

CREATE OR REPLACE FUNCTION "public_testimonial_withdrawal_is_final"() RETURNS trigger
    LANGUAGE plpgsql
    SET search_path = pg_catalog, public
AS $$
BEGIN
    IF OLD."consent_withdrawn_at" IS NULL THEN
        IF NEW."content_erased_at" IS NOT NULL THEN
            RAISE EXCEPTION 'public_testimonial % cannot be erased before consent is withdrawn', OLD."id"
                USING ERRCODE = '23001';
        END IF;

        RETURN NEW;
    END IF;

    IF OLD."content_erased_at" IS NOT NULL THEN
        RAISE EXCEPTION 'public_testimonial % has been erased, and erasure is final', OLD."id"
            USING ERRCODE = '23001';
    END IF;

    IF NEW."content_erased_at" IS NULL
       OR (to_jsonb(NEW) - 'body' - 'author_label' - 'content_erased_at')
          IS DISTINCT FROM (to_jsonb(OLD) - 'body' - 'author_label' - 'content_erased_at') THEN
        RAISE EXCEPTION 'public_testimonial % has had consent withdrawn; the only permitted change is its erasure', OLD."id"
            USING ERRCODE = '23001';
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER "public_testimonial_withdrawal_is_final"
    BEFORE UPDATE ON "public_testimonial"
    FOR EACH ROW EXECUTE FUNCTION "public_testimonial_withdrawal_is_final"();
