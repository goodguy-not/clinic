-- Milestone 10, checkpoint A3 — THE UNATTENDED JOBS, AND THE ERASURES THEY RUN.
--
-- Four jobs run every night (`cli run-jobs`, from a systemd timer):
--
--   WEBSITE_REQUEST_PURGE  the ninety-day erase-in-place (Milestone 9, A4),
--                          unchanged — only now it runs without anybody
--                          remembering to.
--   SESSION_PRUNE          removes staff sessions that ended at least thirty
--                          days ago.
--   MEDIA_ERASURE          owner decision: erases the bytes of a photograph
--                          uploaded thirty days ago and never attached anywhere,
--                          and of one archived by a manager thirty days ago.
--   TESTIMONIAL_ERASURE    owner decision: within seven days of a family
--                          withdrawing consent, erases the testimonial's words
--                          and the bytes of every photograph ever attached to it.
--
-- NOTHING HERE DELETES A HISTORICAL ROW. Every erasure is the erase-in-place
-- pattern `website_request` established: the content columns are cleared, a
-- marker is stamped in the same statement, a CHECK ties the two together, and
-- the row remains to say that something existed and when it was erased. The
-- one physical DELETE is of `user_session`, which was always meant to be
-- prunable (20260803210521_m1_auth_audit) and which no foreign key names.
--
-- THE RUNTIME ROLE GAINS TWO PRIVILEGES, AND A TRIGGER NARROWS EACH TO THE ONE
-- ACT THE JOB PERFORMS (DECISION_LOG, 2026-09-26). A1 anticipated exactly this
-- widening "in its own migration": the jobs run through the same NestJS
-- services as the API, as the same login, so a second role would restate the
-- whole matrix to add two lines.
--
--   DELETE on `user_session`   — `user_session_prune_only_ended` refuses any
--                                row that has not been over for thirty days.
--   UPDATE on `media_rendition` — `media_rendition_erasure_only` refuses every
--                                change but the erasure of a rendition whose
--                                photograph is due for erasure.
--
-- The section above the "HAND-WRITTEN" banner is generated by Prisma.

