-- ===========================================================================
-- HAND-WRITTEN: constraints and triggers Prisma cannot express.
--
-- NOTE ON THE THREE COMPOSITE FOREIGN KEYS ABOVE, WHICH ARE THE UNUSUAL ONES
-- AND ARE THE POINT OF THE LINE TABLE. A closed line copies facts out of three
-- other rows — the period it belongs to, the charge it settles and the rating it
-- was materialised from — and a copy that can disagree with its source is worse
-- than no copy at all, because it is the copy the closed history is read from.
-- Referencing each through a composite key makes the disagreement
-- UNREPRESENTABLE rather than merely checked:
--
--   * `settlement_line_period_scope_fkey` — a line cannot belong to one
--     therapist's period while naming another therapist. A period totalling
--     somebody else's sessions is the error that is only ever noticed by
--     whoever ends up short.
--   * `settlement_line_charge_snapshot_fkey` — the seat, the therapist and the
--     clinic day on the line are the CHARGE's own. It is the shape
--     `session_settlement_charge_snapshot_fkey` already uses, minus the amount:
--     a `CORRECTION` line's `base_amount_toman` is a DELTA and is deliberately
--     not the charge's posted amount, so it cannot be part of the key.
--   * `settlement_line_rating_scope_fkey` — the rating a line was materialised
--     from belongs to the charge the line settles. A line pointing at another
--     session's rating would make the applied percentage on it a fiction.
--
-- `session_charge_settlement_line_snapshot_uq` and
-- `session_settlement_charge_scope_uq` exist only to give those keys a target;
-- both are keyed on their table's primary key first, so neither can refuse a row
-- the primary key would have accepted.
--
-- EVERY FOREIGN KEY IS RESTRICT, and none of the referenced rows is ever
-- deleted: `session_charge` and `session_settlement` both carry no-delete and
-- no-truncate triggers, and so do the two tables here.
-- ===========================================================================

-- --- the range ---------------------------------------------------------------
--
-- BOTH ENDS INCLUSIVE, so a one-day period is `from = to` rather than an empty
-- range. The contract states the same rule and refuses an inverted range before
-- the request reaches the service; this is what makes it true of every writer.
ALTER TABLE "settlement_period" ADD CONSTRAINT "settlement_period_range_chk"
    CHECK ("period_start" <= "period_end");

-- --- the counts --------------------------------------------------------------
--
-- THREE COUNTS, NEVER SUMMED INTO ONE ANOTHER, for the reason the statement's
-- three exception counts are never summed. `settled_session_count` is sessions
-- this close settled for the first time — including historical carry-ins, which
-- are still first settlements. `carried_in_correction_count` is movements
-- against sessions ALREADY settled, which is not work done in this period.
-- `excluded_unrated_session_count` is the number of charged sessions inside the
-- range that carried no rating at the instant of closing, and it is STORED
-- rather than recomputed: recomputing would give a different answer the moment
-- one of them was rated, and the answer that matters is the one that was true
-- when the manager closed.
ALTER TABLE "settlement_period" ADD CONSTRAINT "settlement_period_counts_chk"
    CHECK (
        "settled_session_count" >= 0
        AND "carried_in_correction_count" >= 0
        AND "excluded_unrated_session_count" >= 0
    );

-- --- what the close made final -----------------------------------------------
--
-- `therapist_gross_toman` AND `therapist_discount_toman` DESCRIBE THIS PERIOD'S
-- OWN PRIMARY LINES AND NOTHING ELSE, which is why both are unsigned: a gross is
-- a split of work that happened, and a borne portion of a concession is a
-- non-negative amount. Their difference is this period's own therapist net, and
-- it is never negative — the per-session floor CLAUDE.md states, summed.
--
-- `carried_in_correction_toman` IS THE SIGNED PART, and it is stated separately
-- so the difference between "this period's work" and "last period's correction"
-- is readable on the closed record itself rather than inferred from a single
-- total.
--
-- `settled_toman` IS THE TWO TOGETHER AND IS DERIVED HERE AS A CONSTRAINT rather
-- than trusted to the service: a period whose stated total disagrees with its
-- own components is the one number nobody notices drifting. It may be negative
-- when the corrections carried in outweigh the period's own primaries, and
-- clamping it would state a figure the clinic does not mean. THAT IS NOT A DEBT:
-- this milestone records no money leaving the clinic, so a negative period is a
-- net settlement figure and never a receivable.
ALTER TABLE "settlement_period" ADD CONSTRAINT "settlement_period_totals_chk"
    CHECK (
        "therapist_gross_toman" >= 0
        AND "therapist_discount_toman" >= 0
        AND "therapist_discount_toman" <= "therapist_gross_toman"
        AND "settled_toman"
            = "therapist_gross_toman" - "therapist_discount_toman" + "carried_in_correction_toman"
    );

-- --- overlap prevention ------------------------------------------------------
--
-- AT MOST ONE CLOSED PERIOD MAY COVER A THERAPIST ON ANY GIVEN DAY. This is the
-- constraint the whole checkpoint rests on. An overlap would settle some
-- sessions twice, and silently succeeding — by trimming, merging or
-- reinterpreting the requested range — is how somebody is paid for one session
-- in two months.
--
-- GAPS ARE PERMITTED AND ARE NOT AN ERROR. A clinic that closes Mordad and then
-- Mehr has simply not closed Shahrivar yet, and nothing here or in the service
-- infers a period from the absence of one.
--
-- NOT PARTIAL, unlike every other exclusion constraint in this schema. A share
-- rule and a tariff can be voided and therefore leave the index; a closed period
-- is never reopened, so every row participates forever.
--
-- ENFORCED HERE RATHER THAN BY READING BEFORE WRITING, because that is the
-- difference between an invariant and a convention. Two managers submitting
-- overlapping ranges at the same instant both find the range free if the
-- application checks first; against this constraint exactly one commits.
--
-- `btree_gist` is already installed by the Milestone 2 migration, which needed
-- it for the same reason: a GiST index cannot compare uuid values with `=`
-- without it.
ALTER TABLE "settlement_period" ADD CONSTRAINT "settlement_period_no_overlap_excl"
    EXCLUDE USING GIST (
        "therapist_id" WITH =,
        daterange("period_start", "period_end", '[]') WITH &&
    );

-- --- one authoritative primary settlement per session ------------------------
--
-- A SESSION IS SETTLED EXACTLY ONCE. This is the headline guarantee of the
-- checkpoint and it is a partial unique index rather than a rule the close
-- routine remembers: a session that acquired two `PRIMARY` lines would be a
-- therapist paid twice for one session, discovered by whoever reconciles the
-- year rather than by whoever created it.
--
-- PARTIAL ON `line_type = 'PRIMARY'`, because `CORRECTION` lines are deliberately
-- unbounded in number: a session may move again and again — a concession
-- granted, withdrawn, a rating corrected — and each movement is its own line
-- carried into whichever period was open when it happened.
--
-- IT IS ALSO WHAT MAKES A HISTORICAL CARRY-IN SAFE. A session left unrated by an
-- earlier close carries no line at all, so a later close settles it as the
-- `PRIMARY` it is; this index is what guarantees the "exactly once" half of
-- "exactly once, in a later period".
CREATE UNIQUE INDEX "settlement_line_one_primary_per_charge_uq"
    ON "settlement_line" ("session_charge_id") WHERE ("line_type" = 'PRIMARY');

-- --- what a line type means --------------------------------------------------
--
-- A `PRIMARY` LINE CORRECTS NOTHING AND A `CORRECTION` LINE ALWAYS NAMES WHAT IT
-- CORRECTS. The pointer is the traceability requirement made structural: a
-- correction that named no historical fact would be a signed amount in a period
-- with no way back to the session it reconciles.
ALTER TABLE "settlement_line" ADD CONSTRAINT "settlement_line_type_linkage_chk"
    CHECK (
        ("line_type" = 'PRIMARY' AND "corrects_settlement_line_id" IS NULL)
        OR ("line_type" = 'CORRECTION' AND "corrects_settlement_line_id" IS NOT NULL)
    );

ALTER TABLE "settlement_line" ADD CONSTRAINT "settlement_line_self_correct_chk"
    CHECK ("corrects_settlement_line_id" IS NULL OR "corrects_settlement_line_id" <> "id");

ALTER TABLE "settlement_line" ADD CONSTRAINT "settlement_line_basis_points_chk"
    CHECK ("applied_share_basis_points" >= 0 AND "applied_share_basis_points" <= 10000);

-- --- the split identities, on every line whatever its type -------------------
--
-- THE TWO NET IDENTITIES HOLD FOR A DELTA EXACTLY AS THEY HOLD FOR A LEVEL,
-- because subtraction is linear: if `net = gross - discount` before and after a
-- movement, then the difference of the nets is the difference of the grosses
-- less the difference of the discounts. That is what makes one CHECK cover both
-- line types and what makes a `CORRECTION` line reconcilable against the
-- `PRIMARY` it corrects without a second arithmetic.
--
-- THE GROSS SUM IDENTITY IS THE SAME ONE `session_settlement_split_chk`
-- ENFORCES, carried onto the line: the two sides of a session always add up to
-- what the session was worth.
ALTER TABLE "settlement_line" ADD CONSTRAINT "settlement_line_split_chk"
    CHECK (
        "therapist_net_toman" = "therapist_gross_toman" - "therapist_discount_toman"
        AND "clinic_net_toman" = "clinic_gross_toman" - "clinic_discount_toman"
        AND "therapist_gross_toman" + "clinic_gross_toman" = "base_amount_toman"
    );

-- --- the signs, and where they are allowed -----------------------------------
--
-- A `PRIMARY` LINE IS A LEVEL AND CARRIES THE DOMAIN'S SIGNS. The basis, both
-- grosses and both borne portions are non-negative amounts of real money, and
-- the THERAPIST NET IS NEVER NEGATIVE — CLAUDE.md states that outright, and this
-- is where the rule becomes a property of the closed record rather than of the
-- read that produced it. `clinic_net_toman` is deliberately absent from this
-- list: a clinic that explicitly bears a concession larger than its own gross
-- share has a negative net, and CLAUDE.md requires that subsidy to be VISIBLE.
--
-- A `CORRECTION` LINE IS A DELTA AND EVERY FIGURE ON IT MAY BE NEGATIVE,
-- including the therapist net. That is not a breach of the never-negative rule:
-- the rule is about what a SESSION is worth, and a session whose charge was
-- withdrawn after its period closed is worth nothing now, so the movement that
-- reconciles the closed record to that is `-gross`. The rule is preserved by the
-- invariant below, not by clamping a delta.
ALTER TABLE "settlement_line" ADD CONSTRAINT "settlement_line_primary_signs_chk"
    CHECK (
        "line_type" <> 'PRIMARY'
        OR (
            "base_amount_toman" >= 0
            AND "therapist_gross_toman" >= 0
            AND "clinic_gross_toman" >= 0
            AND "therapist_discount_toman" >= 0
            AND "clinic_discount_toman" >= 0
            AND "therapist_net_toman" >= 0
        )
    );

-- --- a session's lines never sum below zero on the therapist side ------------
--
-- THE NEVER-NEGATIVE RULE, RESTATED WHERE A DELTA CAN REACH IT. `PRIMARY` plus
-- every `CORRECTION` against one session equals what that session is worth NOW,
-- and what a session is worth is never negative on the therapist side. A
-- correction that took the running total below zero would be a closed record
-- asserting that a therapist owes the clinic for a session — precisely the
-- receivable this milestone refuses to model.
--
-- A STATEMENT ABOUT A SUM, SO NOT A CHECK. It reads the sibling rows of the row
-- being inserted, under the lock the close already holds on the charge, and it
-- is the only place the therapist floor can be stated for closed history.
CREATE OR REPLACE FUNCTION "enforce_settlement_line_therapist_floor"() RETURNS trigger
    LANGUAGE plpgsql AS $fn$
DECLARE
    running bigint;
BEGIN
    SELECT coalesce(sum("therapist_net_toman"), 0)
      INTO running
      FROM "settlement_line"
     WHERE "session_charge_id" = NEW."session_charge_id";

    IF running < 0 THEN
        RAISE EXCEPTION
            'settlement_line_therapist_net_floor: settlement lines for session charge % would total % on the therapist side',
            NEW."session_charge_id", running
            USING ERRCODE = 'check_violation',
                  CONSTRAINT = 'settlement_line_therapist_net_floor';
    END IF;

    RETURN NULL;
END;
$fn$;

CREATE CONSTRAINT TRIGGER "settlement_line_enforce_therapist_floor"
    AFTER INSERT ON "settlement_line"
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION "enforce_settlement_line_therapist_floor"();

-- --- a closed primary line always has a valid rating behind it ---------------
--
-- THE CLOSED-LINE RATING INTEGRITY RULE, AND IT IS WHY THIS TRIGGER IS DEFERRED.
--
-- Before this checkpoint a bare rating withdrawal was harmless: nothing
-- permanent downstream depended on it. Once a session carries a closed `PRIMARY`
-- line, the closed figure would be left standing with nothing behind it — and
-- the period is never reopened, so there is no act that could repair it. The
-- session must therefore have a valid applied rating AT ALL TIMES.
--
-- `SessionRatingService.void` refuses the bare withdrawal with
-- `RATING_REPLACEMENT_REQUIRED` and the caller uses the atomic correction
-- instead. That correction withdraws the old rating and inserts its replacement
-- IN ONE TRANSACTION, and in the instant between the two statements the session
-- genuinely has no standing rating — so an ordinary row trigger would refuse the
-- very operation the rule exists to require. A DEFERRED CONSTRAINT TRIGGER asks
-- the question at COMMIT, which is exactly where "at all times" is observable
-- from outside: there is no interval any other transaction can see in which a
-- closed `PRIMARY` has no rating, and there is no inferred zero reversal
-- anywhere.
--
-- IT FIRES FROM BOTH DIRECTIONS, because the invariant can be broken from
-- either: by withdrawing a rating that a line depends on, and by writing a line
-- for a charge whose rating is not standing. One function, two constraint
-- triggers, one rule.
CREATE OR REPLACE FUNCTION "enforce_closed_line_rating_present"() RETURNS trigger
    LANGUAGE plpgsql AS $fn$
DECLARE
    charge_id uuid;
BEGIN
    charge_id := NEW."session_charge_id";

    IF NOT EXISTS (
        SELECT 1 FROM "settlement_line"
         WHERE "session_charge_id" = charge_id AND "line_type" = 'PRIMARY'
    ) THEN
        RETURN NULL;
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM "session_settlement"
         WHERE "session_charge_id" = charge_id AND "voided_at" IS NULL
    ) THEN
        RAISE EXCEPTION
            'settlement_line_requires_valid_rating: session charge % carries a closed primary settlement line and must keep a valid applied rating',
            charge_id
            USING ERRCODE = 'restrict_violation',
                  CONSTRAINT = 'settlement_line_requires_valid_rating';
    END IF;

    RETURN NULL;
END;
$fn$;

CREATE CONSTRAINT TRIGGER "session_settlement_closed_line_rating_present"
    AFTER UPDATE ON "session_settlement"
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION "enforce_closed_line_rating_present"();

CREATE CONSTRAINT TRIGGER "settlement_line_closed_line_rating_present"
    AFTER INSERT ON "settlement_line"
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION "enforce_closed_line_rating_present"();

-- --- no-delete enforcement (reuses the Milestone 1 shared function) ----------
--
-- A closed period and its lines are permanent financial records. There is no
-- withdrawal transition here at all — not even the one `session_settlement` and
-- `session_charge` have — because a closed period is never reopened, so a
-- `voided_at` column would be vocabulary for a capability the product refuses to
-- have. The TRUNCATE trigger is not optional; TRUNCATE bypasses row-level
-- triggers entirely.
CREATE TRIGGER "settlement_period_no_delete"
    BEFORE DELETE ON "settlement_period"
    FOR EACH ROW EXECUTE FUNCTION "raise_append_only_violation"();

CREATE TRIGGER "settlement_period_no_truncate"
    BEFORE TRUNCATE ON "settlement_period"
    FOR EACH STATEMENT EXECUTE FUNCTION "raise_append_only_violation"();

CREATE TRIGGER "settlement_line_no_delete"
    BEFORE DELETE ON "settlement_line"
    FOR EACH ROW EXECUTE FUNCTION "raise_append_only_violation"();

CREATE TRIGGER "settlement_line_no_truncate"
    BEFORE TRUNCATE ON "settlement_line"
    FOR EACH STATEMENT EXECUTE FUNCTION "raise_append_only_violation"();

-- --- immutability, and it is total -------------------------------------------
--
-- NOT ONE PERMITTED TRANSITION, UNLIKE EVERY OTHER FINANCIAL TABLE IN THIS
-- SCHEMA. `session_charge`, `charge_adjustment`, `therapist_share_rule` and
-- `session_settlement` each permit exactly one UPDATE — standing to withdrawn —
-- because each can be taken back. A closed settlement period cannot: it is never
-- reopened, its lines are never edited, and later movement is a NEW line in a
-- LATER period. So the trigger refuses every UPDATE outright, and there is no
-- statement anywhere — from this service, from a migration or from a psql prompt
-- — that can rewrite what was closed.
--
-- `restrict_violation` (SQLSTATE 23001) is the stable code every "the database
-- refuses to rewrite this" guard in this project uses.
CREATE OR REPLACE FUNCTION "enforce_settlement_close_immutability"() RETURNS trigger
    LANGUAGE plpgsql AS $fn$
BEGIN
    RAISE EXCEPTION
        'table % is immutable: a closed settlement period is never reopened and its lines are never rewritten',
        TG_TABLE_NAME
        USING ERRCODE = 'restrict_violation';
END;
$fn$;

CREATE TRIGGER "settlement_period_enforce_immutability"
    BEFORE UPDATE ON "settlement_period"
    FOR EACH ROW EXECUTE FUNCTION "enforce_settlement_close_immutability"();

CREATE TRIGGER "settlement_line_enforce_immutability"
    BEFORE UPDATE ON "settlement_line"
    FOR EACH ROW EXECUTE FUNCTION "enforce_settlement_close_immutability"();

