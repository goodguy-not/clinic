-- Milestone 8, checkpoint C6 — the closed settlement period and its immutable
-- lines.
--
-- WHAT THIS CHECKPOINT ADDS, IN ONE SENTENCE: a manager can draw a permanent
-- line under one therapist's earnings over one explicit inclusive range of
-- clinic days, and the figures that were true at that instant are MATERIALISED
-- as rows that nothing afterwards can rewrite.
--
-- TWO TABLES, AND THE SPLIT IS THE POINT. `settlement_period` is the ACT — who
-- closed what range, when, and the totals the close made final.
-- `settlement_line` is the per-session FACT that act materialised. A period
-- without lines would be a total nobody could reconcile; lines without a period
-- would be facts nobody decided.
--
-- WHY MATERIALISE AT ALL, WHEN C5 DERIVES EVERYTHING BY READING. Because a
-- CLOSE is the one act in this milestone that makes a figure final. C5's
-- statement is a question asked of today's rows and its answer legitimately
-- changes when a concession is granted tomorrow; a closed period must keep
-- saying what it said, which means the numbers have to stop being derived. That
-- is also why every later movement is a NEW row rather than an edit: the
-- correction is carried forward, never written back.
--
-- WHAT IS DELIBERATELY NOT HERE, and none of it is an oversight:
--
--   * NO PAYOUT, PAYABLE, RECEIVABLE OR BALANCE TABLE, AND NO SUCH COLUMN.
--     Milestone 8 records what was EARNED and what has been SETTLED; it records
--     no money leaving the clinic. `settled_toman` means "closed off in a
--     period", never "paid" (contracts `settlement/common.ts`).
--   * NO `status` COLUMN ON `settlement_period`. A row exists only because a
--     close happened, so every row is closed; an `OPEN` state would be a row
--     describing the absence of an act, and the open period is simply the range
--     no closed period covers.
--   * NO REOPEN, NO EDIT, NO DELETE PATH OF ANY KIND. Both tables refuse every
--     UPDATE outright, and both carry the no-delete and no-truncate triggers.
--   * NO COLUMN ADDED TO `session_settlement`, `session_charge` OR
--     `charge_adjustment`. A line points at a rating; a rating knows nothing
--     about periods, and all three immutability triggers are untouched.
--   * NO SERVICE, CHILD OR FAMILY ON A LINE. A settlement line is about work
--     and money between the clinic and one therapist; the service and its
--     duration are the CHARGE's own columns and are joined when a statement
--     needs them, rather than copied into a second undeletable store.
--
-- The section above the "HAND-WRITTEN" banner is generated by Prisma.
-- Everything below it is reviewed by a human, because Prisma cannot express
-- CHECK constraints, exclusion constraints, partial unique indexes or triggers.
-- Each hand-written object is named, and `settlement-close-schema.int-spec.ts`
-- asserts every name exists in the PostgreSQL catalogue, so a future edit cannot
-- quietly drop one.
--
-- THIS MIGRATION IS CREATE-ONLY. It adds one enum, two tables, their indexes and
-- the objects below, plus TWO unique indexes on existing tables that no existing
-- row can violate (both are keyed on the primary key first). It alters no
-- column, drops nothing, and there is nothing to back-fill: every session
-- settled before this migration is UNSETTLED, which is exactly the state the
-- absence of a line means.

