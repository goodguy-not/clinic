-- A relative path to an owner-supplied image, and nothing that could become a
-- request to somewhere else: no scheme, no leading slash, no parent-directory
-- segment. Resolving it to a URL is the web tier's job, which is why nothing
-- here names a host.
ALTER TABLE "therapist" ADD CONSTRAINT "therapist_public_photo_path_chk"
    CHECK (
        "public_photo_path" IS NULL
        OR (
            "public_photo_path" ~ '^[a-z0-9][a-z0-9/._-]*$'
            AND "public_photo_path" NOT LIKE '%..%'
            AND length("public_photo_path") <= 200
        )
    );

-- THE OPT-IN ITSELF, IN ONE CONSTRAINT.
--
-- A public therapist has an address and an approved name to publish under. The
-- reverse is not required: a slug and a display name may be prepared while the
-- person is still private, which is what lets a manager write the content and
-- flip the visibility as two separate, separately audited acts.
ALTER TABLE "therapist" ADD CONSTRAINT "therapist_public_profile_chk"
    CHECK (
        "is_public" IS FALSE
        OR ("public_slug" IS NOT NULL AND "public_display_name" IS NOT NULL)
    );

-- --- slug stability after publication ---------------------------------------
--
-- ONCE A SLUG HAS BEEN REACHABLE, IT IS THE SLUG. `public_first_published_at`
-- is stamped by the trigger the first time a row is `is_public` AND carries a
-- slug; while that stamp is set, the slug may not be changed and may not be
-- cleared.
--
-- REACHABILITY IS `is_public AND public_slug IS NOT NULL`, AND DELIBERATELY
-- SAYS NOTHING ABOUT `status`. A service retired last month still had a real
-- URL last month, and somebody may still have it written down.
--
-- WHAT THIS DELIBERATELY ALLOWS: correcting a slug that has never been
-- published. Preparing the public content and publishing it are two acts (see
-- `therapist_public_profile_chk`), and a typo caught between them is not yet a
-- promise to anybody.
--
-- WHAT IT DELIBERATELY REFUSES: changing the slug of a published row; clearing
-- it; and the round trip — unpublish, change the slug, publish again — which is
-- the same silent URL change with an extra step. Unpublishing itself stays
-- allowed: withdrawing a page is a decision the clinic is entitled to make, and
-- a 404 is honest in a way a moved URL is not.
--
-- NO REDIRECT, ALIAS OR SLUG-HISTORY TABLE IS ADDED, and none is implied. Those
-- are a URL-management subsystem, and the product has not asked for one.

ALTER TABLE "service" ADD CONSTRAINT "service_public_first_published_chk"
    CHECK ("public_first_published_at" IS NULL OR "public_slug" IS NOT NULL);

ALTER TABLE "therapist" ADD CONSTRAINT "therapist_public_first_published_chk"
    CHECK ("public_first_published_at" IS NULL OR "public_slug" IS NOT NULL);

-- One function for both tables: the columns are named identically on purpose,
-- so the rule is stated once and cannot drift between a service and a person.
CREATE OR REPLACE FUNCTION "enforce_public_slug_stability"() RETURNS trigger AS $$
BEGIN
    -- The stamp is the database's, never the caller's: `transaction_timestamp()`
    -- is the same clock every other timestamp in this schema is written with.
    IF NEW."is_public" AND NEW."public_slug" IS NOT NULL
       AND NEW."public_first_published_at" IS NULL THEN
        NEW."public_first_published_at" := transaction_timestamp();
    END IF;

    IF TG_OP = 'UPDATE' AND OLD."public_first_published_at" IS NOT NULL THEN
        IF NEW."public_slug" IS DISTINCT FROM OLD."public_slug" THEN
            RAISE EXCEPTION
                '%.public_slug is immutable once the row has been publicly reachable',
                TG_TABLE_NAME
                USING ERRCODE = '23001';
        END IF;

        IF NEW."public_first_published_at" IS DISTINCT FROM OLD."public_first_published_at" THEN
            RAISE EXCEPTION
                '%.public_first_published_at is written once and never rewritten',
                TG_TABLE_NAME
                USING ERRCODE = '23001';
        END IF;
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER "service_public_slug_stability"
    BEFORE INSERT OR UPDATE ON "service"
    FOR EACH ROW EXECUTE FUNCTION "enforce_public_slug_stability"();

CREATE TRIGGER "therapist_public_slug_stability"
    BEFORE INSERT OR UPDATE ON "therapist"
    FOR EACH ROW EXECUTE FUNCTION "enforce_public_slug_stability"();

-- --- the clinic's own public profile ----------------------------------------

-- ONE ROW, FOR EVER. The primary key plus this CHECK is what makes "the
-- profile" a phrase with exactly one referent, and lets the public read be a
-- lookup that cannot miss.
ALTER TABLE "clinic_public_profile" ADD CONSTRAINT "clinic_public_profile_singleton_chk"
    CHECK ("singleton_key" = 1);

ALTER TABLE "clinic_public_profile" ADD CONSTRAINT "clinic_public_profile_text_chk"
    CHECK (
        ("display_name" IS NULL OR ("display_name" = btrim("display_name") AND btrim("display_name") <> '' AND length("display_name") <= 120))
        AND ("tagline" IS NULL OR ("tagline" = btrim("tagline") AND btrim("tagline") <> '' AND length("tagline") <= 200))
        AND ("about" IS NULL OR ("about" = btrim("about") AND btrim("about") <> '' AND length("about") <= 4000))
        AND ("address_line" IS NULL OR ("address_line" = btrim("address_line") AND btrim("address_line") <> '' AND length("address_line") <= 300))
        AND ("city_label" IS NULL OR ("city_label" = btrim("city_label") AND btrim("city_label") <> '' AND length("city_label") <= 120))
        AND ("phone_primary" IS NULL OR ("phone_primary" = btrim("phone_primary") AND btrim("phone_primary") <> '' AND length("phone_primary") <= 40))
        AND ("phone_secondary" IS NULL OR ("phone_secondary" = btrim("phone_secondary") AND btrim("phone_secondary") <> '' AND length("phone_secondary") <= 40))
        AND ("working_hours_note" IS NULL OR ("working_hours_note" = btrim("working_hours_note") AND btrim("working_hours_note") <> '' AND length("working_hours_note") <= 300))
    );

-- A telephone number is stored exactly as the clinic wants it dialled and is
-- never reformatted; an address is what is written on the door. An e-mail
-- address, by contrast, is machine-readable by definition, so the one shape
-- assertion this table makes is that it looks like one.
ALTER TABLE "clinic_public_profile" ADD CONSTRAINT "clinic_public_profile_email_chk"
    CHECK (
        "email" IS NULL
        OR (
            "email" = btrim("email")
            AND "email" ~ '^[^@[:space:]]+@[^@[:space:]]+[.][^@[:space:]]+$'
            AND length("email") <= 200
        )
    );

-- HTTPS ONLY. These two values are rendered as links on a public page, so a
-- plaintext or `javascript:` value would be a defect with a browser on the
-- other end of it.
ALTER TABLE "clinic_public_profile" ADD CONSTRAINT "clinic_public_profile_links_chk"
    CHECK (
        ("instagram_url" IS NULL OR ("instagram_url" ~ '^https://[^[:space:]]+$' AND length("instagram_url") <= 300))
        AND ("telegram_url" IS NULL OR ("telegram_url" ~ '^https://[^[:space:]]+$' AND length("telegram_url") <= 300))
    );

-- Degrees, WGS 84, and BOTH OR NEITHER: half a coordinate pair is not a
-- location, and a map rendered from one would put the clinic in the sea.
ALTER TABLE "clinic_public_profile" ADD CONSTRAINT "clinic_public_profile_map_chk"
    CHECK (
        ("map_latitude" IS NULL) = ("map_longitude" IS NULL)
        AND ("map_latitude" IS NULL OR "map_latitude" BETWEEN -90 AND 90)
        AND ("map_longitude" IS NULL OR "map_longitude" BETWEEN -180 AND 180)
    );

