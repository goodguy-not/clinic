-- Milestone 9, checkpoint A1 — the public website's foundation.
--
-- WHAT THIS CHECKPOINT ADDS, IN ONE SENTENCE: the clinic can decide which
-- services, which colleagues and which of its own contact facts the world is
-- shown, and every one of those decisions is EXPLICIT, DEFAULTED TO PRIVATE,
-- and enforced by this database rather than by whichever query happens to read
-- it.
--
-- NO NEW TABLE FOR SERVICES OR THERAPISTS, AND THAT IS DELIBERATE. A public
-- service is the service, seen from outside; a second "published service" table
-- would be a copy that drifts, and the first time it drifted the website would
-- be advertising something the clinic had stopped offering. So publication is
-- COLUMNS ON THE ROW ITSELF: intent (`is_public`) and public identity
-- (`public_slug`, and on a therapist the approved display name), and the public
-- read demands all of them at once.
--
-- A THIRD COLUMN RECORDS WHEN THE URL BECAME REAL. `public_first_published_at`
-- is stamped the first time a row is public AND carries a slug, and from that
-- instant the slug is IMMUTABLE — see the stability trigger below. A public URL
-- is a promise to everybody who has already followed it, printed it or linked
-- to it, and this product has no redirect, alias or URL-history machinery to
-- soften a change with. So the change is refused instead.
--
-- ONE NEW TABLE, AND IT HAS EXACTLY ONE ROW. `clinic_public_profile` is the
-- address, telephone number, hours line and links the site prints. It is
-- created EMPTY — every column is nullable and the row inserted at the bottom
-- of this migration carries nothing. This repository does not know the clinic's
-- real address and must not invent one; every value is owner-supplied later,
-- and every fixture that fills them is synthetic.
--
-- THE OPT-IN IS THE PRODUCT RULE THIS MIGRATION EXISTS TO ENFORCE. An active
-- therapist is NOT a public therapist. Appearing on a website with a photograph
-- and a biography is a decision about a named human being, taken with their
-- agreement, so `is_public` defaults to false and
-- `therapist_public_profile_chk` refuses to let it be true without the approved
-- public identity beside it. There is no fallback anywhere in this design: a
-- therapist without an approved public display name is not published, and the
-- personnel record is never substituted for one.
--
-- WHAT IS DELIBERATELY NOT HERE, and none of it is an oversight:
--
--   * NO ARTICLE, TESTIMONIAL OR PAGE TABLE, and no draft/published status
--     column of any kind. Public CONTENT and the workflow that publishes it are
--     later checkpoints; this one freezes the catalogue's public face.
--   * NO WEBSITE REQUEST, CONTACT MESSAGE OR INBOX TABLE. The public request
--     form, its consent capture, its rate limiting and its conversion to a
--     family are later checkpoints, and every one of them touches personal data
--     this checkpoint deliberately does not accept.
--   * NO PRICE AND NO AVAILABILITY ANYWHERE ON THE PUBLIC SIDE. A tariff is
--     effective-dated and may be therapist-specific, and slots live in a diary
--     the website does not read. Publishing either would be a promise the
--     clinic has not made.
--   * NO `updated_at` OR `updated_by_user_id` ON THE NEW TABLE, for the reason
--     no catalog table has them: `audit_log` is the authoritative change
--     history, and a second application-written copy would be the quieter and
--     less trustworthy one.
--   * NO REDIRECT, ALIAS OR SLUG-HISTORY TABLE. A published slug cannot change
--     (see the stability trigger), so there is nothing to redirect FROM. Adding
--     the machinery anyway would be a URL-management subsystem nobody has asked
--     for, and it would quietly make the slug mutable again.
--   * NO PARTIAL LISTING INDEX. The clinic's catalogue is tens of rows; the two
--     unique slug indexes serve every lookup, and an index tuned for the list
--     read would be tuning nobody has measured.
--
-- THIS MIGRATION IS ADDITIVE AND BACK-FILLS NOTHING. Every column it adds is
-- either nullable or defaulted, no existing row can violate any constraint
-- below, and no existing service or therapist becomes public: a service already
-- flagged `is_public` gains a NULL slug and therefore stays unreachable from
-- the website until a manager gives it an address. That is the safe direction —
-- the alternative would have published rows on the strength of a flag nobody
-- set with a website in mind.
--
-- The section above the "HAND-WRITTEN" banner is generated by Prisma.
-- Everything below it is reviewed by a human, because Prisma cannot express
-- CHECK constraints or triggers. Each hand-written object is named, and
-- `public-catalog-schema.int-spec.ts` asserts every name exists in the
-- PostgreSQL catalogue, so a future edit cannot quietly drop one.

