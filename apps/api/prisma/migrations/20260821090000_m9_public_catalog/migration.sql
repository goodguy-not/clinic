-- --- the public slug --------------------------------------------------------
--
-- Lowercase ASCII words joined by single hyphens, two to eighty characters —
-- the same pattern the shared contract enforces (`publicSlugSchema`).
--
-- ASCII IN A PERSIAN PRODUCT, DELIBERATELY. The slug is the URL, and a URL is
-- compared byte for byte by every cache, log, sitemap and canonical tag that
-- will ever see it; Persian in a path is percent-encoded by the browser and
-- normalised differently by different clients, so two links to one page would
-- stop being one string. The Persian a visitor READS lives in the display
-- columns beside it.
--
-- The UNIQUE indexes above are across ALL rows — private and inactive ones
-- included — so a slug that ever addressed one page can never quietly be moved
-- to another. NULLs are distinct in PostgreSQL, so any number of rows may
-- remain unpublished.

ALTER TABLE "service" ADD CONSTRAINT "service_public_slug_chk"
    CHECK (
        "public_slug" IS NULL
        OR (
            "public_slug" ~ '^[a-z0-9]+(-[a-z0-9]+)*$'
            AND length("public_slug") BETWEEN 2 AND 80
        )
    );

ALTER TABLE "therapist" ADD CONSTRAINT "therapist_public_slug_chk"
    CHECK (
        "public_slug" IS NULL
        OR (
            "public_slug" ~ '^[a-z0-9]+(-[a-z0-9]+)*$'
            AND length("public_slug") BETWEEN 2 AND 80
        )
    );

