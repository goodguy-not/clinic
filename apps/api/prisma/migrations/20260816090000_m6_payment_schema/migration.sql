-- --- financial immutability ---------------------------------------------------
--
-- The same model `enforce_session_charge_immutability` established. Everything a
-- payment says about which family paid, how much, by what method and on which
-- day is written once. EXACTLY ONE TRANSITION IS PERMITTED: active to voided.
--
-- Correcting a payment is therefore void-and-re-record, not an edit, and both
-- rows survive — including a payment entered against the wrong day, which is
-- corrected the same way (DECISION_LOG, 2026-08-15).
--
-- The NOTE AND THE REFERENCE ARE FROZEN TOO. They are part of what the record
-- says about money that changed hands, and a note quietly rewritten after the
-- fact is exactly the class of edit a financial trail exists to refuse.
--
-- Unvoiding, and revising a void reason or actor after the fact, are refused
-- with the same `restrict_violation` (SQLSTATE 23001) every "the database
-- refuses to rewrite this" failure in this project raises.
CREATE OR REPLACE FUNCTION "enforce_payment_immutability"() RETURNS trigger
    LANGUAGE plpgsql AS $fn$
BEGIN
    IF NEW."id"                 IS DISTINCT FROM OLD."id"
        OR NEW."family_id"          IS DISTINCT FROM OLD."family_id"
        OR NEW."amount_toman"       IS DISTINCT FROM OLD."amount_toman"
        OR NEW."method"             IS DISTINCT FROM OLD."method"
        OR NEW."received_on"        IS DISTINCT FROM OLD."received_on"
        OR NEW."reference"          IS DISTINCT FROM OLD."reference"
        OR NEW."note"               IS DISTINCT FROM OLD."note"
        OR NEW."created_at"         IS DISTINCT FROM OLD."created_at"
        OR NEW."created_by_user_id" IS DISTINCT FROM OLD."created_by_user_id"
    THEN
        RAISE EXCEPTION
            'payment % is immutable; only a single void transition is permitted', OLD."id"
            USING ERRCODE = 'restrict_violation';
    END IF;

    IF OLD."voided_at" IS NOT NULL
        AND (
            NEW."voided_at"          IS DISTINCT FROM OLD."voided_at"
            OR NEW."voided_by_user_id" IS DISTINCT FROM OLD."voided_by_user_id"
            OR NEW."void_reason"       IS DISTINCT FROM OLD."void_reason"
        )
    THEN
        RAISE EXCEPTION
            'payment % is already voided; the void cannot be changed or reversed', OLD."id"
            USING ERRCODE = 'restrict_violation';
    END IF;

    RETURN NEW;
END;
$fn$;

CREATE TRIGGER "payment_enforce_immutability"
    BEFORE UPDATE ON "payment"
    FOR EACH ROW EXECUTE FUNCTION "enforce_payment_immutability"();

