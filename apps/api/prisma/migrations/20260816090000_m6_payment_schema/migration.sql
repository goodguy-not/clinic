-- ===========================================================================
-- HAND-WRITTEN — everything below this line is reviewed by a human, not
-- generated.
--
-- NOTE ON THE FOREIGN KEYS: they are generated above rather than written here,
-- for the reason recorded in DECISION_LOG 2026-08-06 — Prisma DOES see foreign
-- keys, unlike CHECK constraints, partial indexes and triggers, so a
-- hand-written one reads as permanent schema drift and fails CI on every run.
-- Two of them are load-bearing domain rules rather than plumbing:
--
--   * `(fulfilling_payment_id, family_id)` -> `payment(id, family_id)` proves
--     THE PAYMENT THAT FULFILS A PROMISE BELONGS TO THE SAME FAMILY. The
--     single-column key would have let one family's promise be settled with
--     another family's money, and no amount of service-layer care makes that a
--     guarantee. Exactly the shape `session_charge_child_id_family_id_fkey`
--     uses, for exactly the same reason;
--   * `(rescheduled_to_promise_id, family_id)` -> `payment_promise(id,
--     family_id)` says the same thing about a successor: a family's promise is
--     never rescheduled into another family's.
--
-- Both are ON DELETE RESTRICT, like everything else financial here, and both
-- reference a `(id, family_id)` unique index that asserts no new uniqueness —
-- each is unique on a superset of a primary key that is unique already, and
-- exists solely as a target the composite key can reference.
--
-- WHY `fulfilling_payment_id` IS UNIQUE. One payment fulfils at most one
-- promise (DECISION_LOG, 2026-08-15 — A promise is a calendar fact). That is
-- what keeps the evidence unambiguous without the allocation table this
-- milestone refused: a payment cannot be spent twice as proof, and there is no
-- partial-fulfilment model to reconcile. `rescheduled_to_promise_id` is unique
-- for the mirror reason — a successor succeeds at most one promise.
--
-- WHY THE SUCCESSOR LINK POINTS FORWARD, from the old promise to the new one,
-- and not backward. It makes the reschedule ONE STATEMENT: the same UPDATE that
-- sets `status = 'RESCHEDULED'` names the successor, so PostgreSQL can assert
-- the biconditional below — a rescheduled promise always has exactly one
-- successor, and a promise that has a successor is always rescheduled. A
-- backward link on the successor could not express either half: the predecessor
-- would be free to stay OPEN with a successor already live, which is two open
-- promises for one intention.
--
-- THE WHOLE CHAIN GUARANTEE, and where each half of it is enforced. A raw caller
-- with a psql session cannot produce any of these:
--
--   * a successor that has already ended            -> transition trigger, which
--                                                      requires the successor be
--                                                      OPEN;
--   * a successor in another family                 -> the composite foreign key
--                                                      `(rescheduled_to_promise_id,
--                                                      family_id)`;
--   * one successor reused by two predecessors      -> `..._rescheduled_to_promise_id_key`,
--                                                      unique;
--   * a promise as its own successor                -> `..._reschedule_link_chk`;
--   * a CYCLE, at any depth                         -> falls out of the OPEN rule
--                                                      above: a rescheduled
--                                                      promise is terminal and can
--                                                      never afterwards be named as
--                                                      anybody's successor, so a
--                                                      chain only extends from an
--                                                      ended promise into an open
--                                                      one and can never return;
--   * a BACKWARDS chain                             -> the successor may not
--                                                      predate the promise it
--                                                      supersedes;
--   * RESCHEDULED with no successor, or a successor
--     with some other status                        -> `..._reschedule_link_chk`,
--                                                      biconditional;
--   * the link changed, cleared or repointed after
--     the fact                                      -> the transition trigger
--                                                      refuses EVERY update to a
--                                                      row that has already ended;
--   * either row edited so the history stops making
--     sense                                         -> amount, due date, family,
--                                                      note and creation facts are
--                                                      frozen on both rows, and
--                                                      neither can be deleted.
--
-- NONE OF THAT NEEDS A RECURSIVE OR TEMPORAL TRIGGER. Every guarantee is either
-- a declarative constraint or a single-row lookup in the one trigger that
-- already had to exist, which is why the forward link was kept rather than
-- traded for the back-reference shape: the back-reference would need its own
-- trigger to close the two-open-promises hole and would still not make the
-- biconditional expressible.
--
-- ----------------------------------------------------------------------------
-- NOTE ON LOCK ORDER. Milestone 4 fixed the global order, and Milestone 5
-- extended it with the financial tables. Milestone 6 extends it once more, at
-- the end, before the advisory keys:
--
--     appointment -> service -> therapist -> room -> family -> child
--                 -> session_charge -> charge_adjustment
--                 -> payment_promise -> payment
--                 -> advisory keys
--
-- THE PROMISE IS LOCKED BEFORE THE PAYMENT, and only one operation in this
-- milestone needs both rows: fulfilment. `enforce_payment_promise_transition`
-- runs on an UPDATE of `payment_promise` — which has already taken the row lock
-- on the promise — and then takes `FOR SHARE` on the payment it is being
-- fulfilled by. Nothing takes them the other way round:
--
--   * RECORDING a payment reads no promise;
--   * VOIDING a payment is an UPDATE on `payment` alone. It takes NO promise
--     lock and performs NO promise read — not to check anything, and not to
--     build history or audit context, which A2 assembles from the payment row
--     and its own log. A guard there would be the `payment -> payment_promise`
--     direction this order forbids, and it would also be wrong: see the note on
--     what is not constrained, at the foot of this file;
--   * RESCHEDULING touches `payment_promise` twice and `payment` never. Within
--     this one table the order is PREDECESSOR then SUCCESSOR — the UPDATE locks
--     the promise being closed, and the trigger then locks the successor it
--     names. In the approved flow the successor is a row inserted moments
--     earlier in the same transaction and is therefore uncontended.
--
-- Nothing here takes an advisory lock. Both cross-row guarantees are a unique
-- index or a row lock, so neither needs one.
-- ----------------------------------------------------------------------------
-- ===========================================================================

-- --- payment: money, bounded and positive -----------------------------------
--
-- The same 1,000,000,000-toman ceiling `tariff_price_bounds_chk` and
-- `session_charge_amount_bounds_chk` use, and for the same reason: a fat-finger
-- guard, not a modelled maximum. Integer toman in BIGINT throughout
-- (DECISION_LOG, 2026-08-02 — Money unit).
--
-- STRICTLY POSITIVE, unlike a charge, which may legitimately be zero when the
-- session was genuinely complimentary. There is no such thing as a payment of
-- nothing, and a refund is not a negative payment — it is a different fact with
-- different rules and no approved shape in this milestone.

ALTER TABLE "payment" ADD CONSTRAINT "payment_amount_bounds_chk"
    CHECK ("amount_toman" > 0 AND "amount_toman" <= 1000000000);

-- Optional, and normalised where present: the same three-part rule every
-- optional text in this schema carries, so an empty string and a padded one
-- cannot both mean "absent".
--
-- 40 CHARACTERS, WHICH IS THE `legacy_paper_file_number` BOUND. A bank or
-- terminal reference is the same KIND of value as that one — a short identifier
-- an operator transcribes from somewhere else — and 40 is the length this
-- repository already uses for exactly that. It comfortably holds a terminal
-- trace, a transfer id, a receipt number or a 26-character IBAN, and refuses a
-- pasted statement line. The 120-character bound this constraint carried in the
-- first draft was borrowed from `guardian_relationship_note_chk`, which bounds a
-- short piece of PROSE; names and notes are a different family of value from
-- identifiers, and matching the wrong one is how a limit becomes arbitrary.
--
-- The value is stored HERE and is deliberately never copied into an audit
-- payload (DECISION_LOG, 2026-08-15 — Payment and promise audit carries no bank
-- reference). `audit_log` is append-only and permanent, so a banking identifier
-- written into it becomes a second undeletable store of that identifier, kept to
-- answer a question the payment id already answers.
ALTER TABLE "payment" ADD CONSTRAINT "payment_reference_chk"
    CHECK (
        "reference" IS NULL
        OR (
            "reference" = btrim("reference")
            AND btrim("reference") <> ''
            AND length("reference") <= 40
        )
    );

-- Mirrors `family_note_chk` and `appointment_note_chk` exactly, because it is
-- the same kind of value. Unlike the reference, a note IS the fact, so audit
-- writes it in full.
ALTER TABLE "payment" ADD CONSTRAINT "payment_note_chk"
    CHECK (
        "note" IS NULL
        OR (
            "note" = btrim("note")
            AND btrim("note") <> ''
            AND length("note") <= 2000
        )
    );

-- A void is one fact stated whole: who, when, and why. Identical to
-- `session_charge_void_consistency_chk`, because voiding a payment is the same
-- act on the same kind of record.
ALTER TABLE "payment" ADD CONSTRAINT "payment_void_consistency_chk"
    CHECK (
        (
            "voided_at" IS NULL
            AND "voided_by_user_id" IS NULL
            AND "void_reason" IS NULL
        )
        OR (
            "voided_at" IS NOT NULL
            AND "voided_by_user_id" IS NOT NULL
            AND "void_reason" IS NOT NULL
            AND "void_reason" = btrim("void_reason")
            AND btrim("void_reason") <> ''
            AND length("void_reason") <= 500
        )
    );

-- --- money does not arrive tomorrow ------------------------------------------
--
-- `received_on` is the day the money arrived. It may be BACK-DATED without any
-- age limit — money that arrived on Thursday and is entered on Saturday arrived
-- on Thursday, and refusing that would push the clinic to enter a false date —
-- and it may NEVER be in the future, because a future receipt records money that
-- does not exist yet. That is a promise, and `payment_promise` already models
-- one (DECISION_LOG, 2026-08-15 — A payment may be back-dated but never
-- post-dated).
--
-- A TRIGGER RATHER THAN A CHECK, and not by preference. The comparison must be
-- against the CLINIC's business date in Asia/Tehran, which is what
-- `clinic_date()` answers, and that function is STABLE rather than IMMUTABLE —
-- deliberately, because timezone definitions can change (Milestone 3).
-- PostgreSQL will not accept a non-immutable function in a CHECK, and comparing
-- against `CURRENT_DATE` instead would use the session's timezone, which differs
-- from the clinic's for three and a half hours of every day.
--
-- INSERT ONLY. `received_on` is frozen by the immutability trigger below, so
-- there is no update path for this rule to guard, and re-evaluating it on every
-- void would mean a payment correctly entered yesterday could not be voided
-- today.
CREATE OR REPLACE FUNCTION "enforce_payment_received_on"() RETURNS trigger
    LANGUAGE plpgsql AS $fn$
BEGIN
    IF NEW."received_on" > clinic_date() THEN
        RAISE EXCEPTION
            'payment % is dated %, after the clinic business date %; money that has not arrived is a promise, not a payment',
            NEW."id", NEW."received_on", clinic_date()
            USING ERRCODE = 'check_violation';
    END IF;

    RETURN NEW;
END;
$fn$;

CREATE TRIGGER "payment_enforce_received_on"
    BEFORE INSERT ON "payment"
    FOR EACH ROW EXECUTE FUNCTION "enforce_payment_received_on"();

