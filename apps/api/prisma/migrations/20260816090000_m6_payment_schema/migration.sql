-- --- the one transition, and everything it has to be true for -----------------
--
-- A promise changes exactly once, out of OPEN, and this is the single place that
-- can happen. It carries three jobs that no CHECK can do:
--
--   1. IMMUTABILITY. Amount, due date, family, note and the creation facts are
--      written once. "Rescheduling preserves old due-date history"
--      (PROJECT_SPEC.md 8) is exactly this: the old promise cannot be edited into
--      the new one, so the history is two rows and not one rewritten one.
--
--   2. TERMINAL IS TERMINAL. A FULFILLED, RESCHEDULED or CANCELLED row cannot
--      transition again — not to another terminal state, and not back to OPEN.
--
--   3. THE FULFILMENT INVARIANTS, which span two rows and therefore cannot be a
--      CHECK. The linked payment must exist, must not be voided, and must be at
--      least the promised amount. The same-family half is the composite foreign
--      key above; that one PostgreSQL can express declaratively, so it does.
--
-- IN THE DATABASE AND NOT ONLY IN THE SERVICE, which does not exist yet — the
-- same standard `enforce_charge_adjustment_bounds` set for the effective-charge
-- floor. A rule that arrives with its first caller is a rule the second caller
-- can forget, and these must hold for the repair script and the psql session too.
--
-- ON THE LOCKS, and the order they are taken in:
--
--   * the promise row is ALREADY LOCKED when this runs — it is the row being
--     updated — so the promise is always the first lock, which is the approved
--     `payment_promise -> payment` direction;
--   * the payment is taken `FOR SHARE`, not `FOR UPDATE`. FOR SHARE is exactly
--     strong enough: it blocks the UPDATE that would void the payment, so a void
--     racing a fulfilment cannot slip between the check and the commit, and two
--     fulfilments naming the same payment do NOT block each other pointlessly —
--     the unique index on `fulfilling_payment_id` is what refuses the second, and
--     it does so correctly under concurrency without any lock of its own;
--   * it is taken in a BEFORE trigger, which runs ahead of the foreign key's own
--     check on the same row, so the stronger lock is always the first acquired;
--   * the successor, on a reschedule, is taken `FOR UPDATE` so it cannot be
--     cancelled or fulfilled concurrently with being named. It is a
--     `payment_promise` row, so this is an intra-table order — predecessor, then
--     successor — and never the forbidden direction.
CREATE OR REPLACE FUNCTION "enforce_payment_promise_transition"() RETURNS trigger
    LANGUAGE plpgsql AS $fn$
DECLARE
    payment_amount       bigint;
    payment_voided       timestamptz;
    successor_status     "payment_promise_status";
    successor_due_on     date;
    successor_created_at timestamptz;
BEGIN
    IF NEW."id"                 IS DISTINCT FROM OLD."id"
        OR NEW."family_id"          IS DISTINCT FROM OLD."family_id"
        OR NEW."amount_toman"       IS DISTINCT FROM OLD."amount_toman"
        OR NEW."due_on"             IS DISTINCT FROM OLD."due_on"
        OR NEW."note"               IS DISTINCT FROM OLD."note"
        OR NEW."created_at"         IS DISTINCT FROM OLD."created_at"
        OR NEW."created_by_user_id" IS DISTINCT FROM OLD."created_by_user_id"
    THEN
        RAISE EXCEPTION
            'payment promise % is immutable; only a single transition out of OPEN is permitted',
            OLD."id"
            USING ERRCODE = 'restrict_violation';
    END IF;

    IF OLD."status" <> 'OPEN' THEN
        RAISE EXCEPTION
            'payment promise % is already %; a promise that has ended cannot transition again',
            OLD."id", OLD."status"
            USING ERRCODE = 'restrict_violation';
    END IF;

    -- Still OPEN, and nothing above changed: the resolution CHECK forces the
    -- link and actor columns to stay null while a promise is open, so there is
    -- nothing left for such an UPDATE to have altered.
    IF NEW."status" = 'OPEN' THEN
        RETURN NEW;
    END IF;

    -- EACH BRANCH GUARDS ON ITS OWN LINK BEING PRESENT, and that is not
    -- redundant with the biconditional CHECKs above: a BEFORE trigger runs
    -- ahead of every CHECK, so without the guard a `RESCHEDULED` row naming no
    -- successor would be refused here — correctly, but as a missing foreign key
    -- rather than as the violated CHECK it actually is. The declarative
    -- constraint owns "a terminal state must name its link"; this trigger owns
    -- what must be true OF the link.
    IF NEW."status" = 'FULFILLED' AND NEW."fulfilling_payment_id" IS NOT NULL THEN
        SELECT "amount_toman", "voided_at"
          INTO payment_amount, payment_voided
          FROM "payment"
         WHERE "id" = NEW."fulfilling_payment_id"
           FOR SHARE;

        IF NOT FOUND THEN
            RAISE EXCEPTION 'payment % does not exist', NEW."fulfilling_payment_id"
                USING ERRCODE = 'foreign_key_violation';
        END IF;

        -- A voided payment is money the clinic says it never received. It
        -- cannot be evidence that a promise was kept.
        IF payment_voided IS NOT NULL THEN
            RAISE EXCEPTION
                'payment % is voided and cannot fulfil promise %',
                NEW."fulfilling_payment_id", OLD."id"
                USING ERRCODE = 'restrict_violation';
        END IF;

        -- There is no partial fulfilment (DECISION_LOG, 2026-08-15). A payment
        -- that does not cover the promise leaves it open; the family who pays in
        -- instalments reschedules or cancels instead. A LARGER payment fulfils
        -- in full and the surplus is visible as derived credit, not as a
        -- remainder recorded against this promise.
        IF payment_amount < OLD."amount_toman" THEN
            RAISE EXCEPTION
                'payment % of % toman is smaller than the % toman promised by %',
                NEW."fulfilling_payment_id", payment_amount, OLD."amount_toman", OLD."id"
                USING ERRCODE = 'check_violation';
        END IF;
    END IF;

    IF NEW."status" = 'RESCHEDULED' AND NEW."rescheduled_to_promise_id" IS NOT NULL THEN
        SELECT "status", "due_on", "created_at"
          INTO successor_status, successor_due_on, successor_created_at
          FROM "payment_promise"
         WHERE "id" = NEW."rescheduled_to_promise_id"
           FOR UPDATE;

        IF NOT FOUND THEN
            RAISE EXCEPTION 'payment promise % does not exist', NEW."rescheduled_to_promise_id"
                USING ERRCODE = 'foreign_key_violation';
        END IF;

        -- The successor is the promise that now stands. One already ended
        -- cannot be it.
        --
        -- THIS IS ALSO THE WHOLE CYCLE PROOF. A promise that has been rescheduled
        -- is RESCHEDULED, which is terminal, so it can never afterwards be named
        -- as anybody's successor. A chain therefore only ever extends forward
        -- from an ended promise into an open one, and A -> B -> ... -> A is
        -- unreachable — no depth-walking trigger and no temporal reasoning
        -- required to say so.
        IF successor_status <> 'OPEN' THEN
            RAISE EXCEPTION
                'payment promise % is %, and cannot be the successor of %',
                NEW."rescheduled_to_promise_id", successor_status, OLD."id"
                USING ERRCODE = 'restrict_violation';
        END IF;

        -- NO BACKWARDS CHAINS. Rescheduling CREATES the promise that follows, so
        -- the successor cannot predate the promise it supersedes. Without this,
        -- two promises that happen to be open at once could be wired into a
        -- history that runs backwards through time — legal against every other
        -- rule here, and nonsense to read.
        --
        -- `<` and not `<=`: in the approved flow the successor is inserted
        -- moments earlier in the SAME transaction, so both rows carry the same
        -- `transaction_timestamp()` and equality is the normal case.
        IF successor_created_at < OLD."created_at" THEN
            RAISE EXCEPTION
                'payment promise % was created before %, and cannot be its successor; rescheduling creates the promise that follows',
                NEW."rescheduled_to_promise_id", OLD."id"
                USING ERRCODE = 'check_violation';
        END IF;

        -- Rescheduling is a new intention agreed NOW, and an intention already
        -- overdue at the moment it is agreed records nothing. This is the one
        -- date rule an initial promise does not have.
        IF successor_due_on < clinic_date() THEN
            RAISE EXCEPTION
                'payment promise % is due on %, before the clinic business date %; a rescheduled promise may not be agreed already overdue',
                NEW."rescheduled_to_promise_id", successor_due_on, clinic_date()
                USING ERRCODE = 'check_violation';
        END IF;
    END IF;

    RETURN NEW;
END;
$fn$;

CREATE TRIGGER "payment_promise_enforce_transition"
    BEFORE UPDATE ON "payment_promise"
    FOR EACH ROW EXECUTE FUNCTION "enforce_payment_promise_transition"();

-- --- no-delete enforcement (reuses the Milestone 1 shared function) ----------
--
-- "Final financial records are voided or adjusted, never physically deleted"
-- (CLAUDE.md; PROJECT_SPEC.md 7). A payment is money and the rule is absolute
-- for it. A promise is not money, and is protected identically anyway: it is a
-- recorded commitment a family made, its whole value is the history it keeps,
-- and it is ended by CANCELLED — a state that says so — rather than by
