-- Milestone 6, checkpoint A1 — the payment schema and promise integrity
-- foundation.
--
-- TWO TABLES. `payment` is money the clinic received from one family;
-- `payment_promise` is a family's stated intention to pay, which moves no money
-- in any state.
--
-- STRUCTURE ONLY. This checkpoint builds the schema for both and the behaviour
-- of neither: there is no payment service, no endpoint, no permission, no error
-- vocabulary, no audit action and no family account position. The tables exist
-- now so the checkpoints that add those behaviours do not each open with a
-- migration, and so the shape of money-in is settled before any of it exists.
--
-- WHAT IS DELIBERATELY NOT HERE. No payment allocation, no stored balance, no
-- stored credit, no invoice, no settlement, no payment cache, no therapist-share
-- column, no opening-balance table and no `follow_up_date`. Each was refused by
-- name in DECISION_LOG on 2026-08-15, and `payment-schema.int-spec.ts` asserts
-- the refusals hold.
--
--   * ALLOCATION. A payment is a family fact and settles no particular charge.
--     Therapist settlement is completed-session value and independent of payment
--     (DECISION_LOG, 2026-08-02), which removed the only domain need for it; an
--     allocation table would be a second, editable account of the same money
--     that can disagree with the first.
--   * STORED BALANCE AND STORED CREDIT. Both are sums of rows that already
--     exist. A cached total can drift from what produces it, and there is no
--     read volume here that makes the derivation expensive.
--   * A `status` COLUMN ON `payment`. The lifecycle is exactly CONFIRMED then
--     VOIDED, with no stored PENDING, and that is the same two-state shape
--     `session_charge` carries. It is spelled the same way — a payment is
--     confirmed exactly while `voided_at` is null — because a status enum
--     alongside the void triple is two accounts of one fact, and two accounts
--     can disagree. The word CONFIRMED is derived at the contract boundary.
--
-- The section above the "HAND-WRITTEN" banner is generated by Prisma.
-- Everything below it is reviewed by a human, because Prisma cannot express
-- CHECK constraints or triggers. Each hand-written object is named, and
-- `payment-schema.int-spec.ts` asserts every name exists in the PostgreSQL
-- catalogue, so a future edit cannot quietly drop one.
--
-- THIS MIGRATION IS CREATE-ONLY. It adds two enums, two tables, their indexes
-- and the objects below; it alters no existing column and drops nothing, so it
-- cannot fail on existing data and there is nothing to back-fill.
--
-- ON TIMESTAMPS: as in all five earlier migrations, `CURRENT_TIMESTAMP` is
-- PostgreSQL's exact synonym for `transaction_timestamp()`, left spelled as
-- Prisma generates it so drift detection cannot produce a false positive on a
-- synonym. `received_on` and `due_on` are the two dates here that are not clock
-- readings: both are clinic calendar days in Asia/Tehran, which is what
-- `clinic_date()` answers.

