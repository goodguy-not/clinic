-- NOTE ON WHAT IS NOT CONSTRAINED HERE, deliberately:
--
--   * A FULFILLING PAYMENT BEING VOIDED AFTERWARDS. The invariant "the linked
--     payment is not voided" is checked AT FULFILMENT and is not re-checked when
--     the payment is later voided. Two reasons, and the second is the stronger:
--
--       - a guard in the payment's own trigger would have to reach into
--         `payment_promise`, which is the `payment -> payment_promise` direction
--         the approved lock order forbids;
--       - and it would be wrong on the domain. A terminal promise cannot
--         transition again, so a FULFILLED promise can never be reopened. If the
--         database also refused to void its payment, a payment recorded in error
--         against a promise would be PERMANENTLY UNVOIDABLE — and void is the
--         only correction a payment has (DECISION_LOG, 2026-08-15 — A payment is
--         confirmed or voided). The cure would be worse than the condition.
--
--     Nothing financial breaks: a promise never affects any total in any state,
--     so a voided fulfilling payment leaves every balance correct and makes one
--     historical promise's evidence stale, visibly and auditably. The read models
--     from A2 onward should show the linked payment's own state rather than
--     assert that a FULFILLED promise was paid.
--
--   * MISSED. Not a state, not a column, not a job. An OPEN promise whose due
--     date has passed, derived on read.
--
--   * A SUCCESSOR'S AMOUNT relating to its predecessor's. No approved rule says
--     a rescheduled promise is for the same money, and inventing one would refuse
--     the renegotiation that is the commonest reason to reschedule.
--
--   * PAYMENT AGAINST BALANCE, in either direction. A payment may be smaller or
--     larger than what is owed (PROJECT_SPEC.md 8), overpayment is credit, and
--     the balance is derived — so there is no stored quantity here to compare
--     against, by design.
--
--   * WHO MAY RECORD OR VOID. A receptionist records, a manager voids
--     (DECISION_LOG, 2026-08-15 — Payment void is manager-only). That is
--     authorization, it belongs to the API surface, and A2 owns it; the database
--     records which actor did what and does not decide who was allowed to.
--
-- NOTE ON COMPLETENESS: as in all five earlier migrations, a table owner can
-- still run `ALTER TABLE ... DISABLE TRIGGER`. Closing that gap needs a runtime
-- database role that does not own these tables, and remains a production
-- hardening item.
