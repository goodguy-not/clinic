-- THE RESOLUTION, STATED WHOLE: who ended the promise, when, and — where the
-- ending was a decision rather than an outcome — why.
--
-- THE REASON LIVES ON THE PROMISE, NOT ONLY IN THE AUDIT TRAIL. Rescheduling and
-- cancelling are explicit historical resolutions, and "why was this promise
-- cancelled?" is a question about the promise. Answering it only from
-- `audit_log` would make the domain record incomplete on its own terms and would
-- put a fact the clinic reads routinely behind a table meant for investigation.
-- The trail still records the action; this records the record.
--
--   * OPEN               — no actor, no instant, NO REASON. Nothing has ended.
--   * RESCHEDULED        — reason MANDATORY. A new date was agreed instead of
--                          the old one, and the old promise must say what that
--                          was about.
--   * CANCELLED          — reason MANDATORY, for the same reason and more so:
--                          a promise abandoned with no explanation is exactly
--                          what CLAUDE.md forbids of a correction.
--   * FULFILLED          — reason OPTIONAL. The promise did what it said, the
--                          linked payment is the explanation, and demanding
--                          prose for a kept promise would produce prose nobody
--                          means.
--
-- Bounded at 500 characters, the length every other reason in this schema
-- carries — `void_reason`, `free_reason`, `cancellation_reason`,
-- `availability_override_reason` and `charge_adjustment.reason`.
--
-- SPLIT INTO TWO CONSTRAINTS on purpose: one says WHEN a reason must be present,
-- the other says what a reason must LOOK like. A single combined condition would
-- have to restate the text rules under each status branch, and a rule stated
-- four times is a rule that gets edited three times.
ALTER TABLE "payment_promise" ADD CONSTRAINT "payment_promise_resolution_chk"
    CHECK (
        (
            "status" = 'OPEN'
            AND "resolved_at" IS NULL
            AND "resolved_by_user_id" IS NULL
            AND "resolution_reason" IS NULL
        )
        OR (
            "status" <> 'OPEN'
            AND "resolved_at" IS NOT NULL
            AND "resolved_by_user_id" IS NOT NULL
            AND ("status" = 'FULFILLED' OR "resolution_reason" IS NOT NULL)
        )
    );

ALTER TABLE "payment_promise" ADD CONSTRAINT "payment_promise_resolution_reason_chk"
    CHECK (
        "resolution_reason" IS NULL
        OR (
            "resolution_reason" = btrim("resolution_reason")
            AND btrim("resolution_reason") <> ''
            AND length("resolution_reason") <= 500
        )
    );

-- FULFILLED IF AND ONLY IF A PAYMENT IS NAMED. Not "may carry a link": a
-- fulfilment with no payment is a claim nobody can check, and a payment linked
-- to a promise that is not fulfilled is evidence for nothing. Biconditional, so
-- neither half can drift from the other.
ALTER TABLE "payment_promise" ADD CONSTRAINT "payment_promise_fulfilment_link_chk"
    CHECK (("status" = 'FULFILLED') = ("fulfilling_payment_id" IS NOT NULL));

-- RESCHEDULED IF AND ONLY IF A SUCCESSOR IS NAMED, which is what makes
-- "rescheduling preserves the old promise" (PROJECT_SPEC.md 8) structural: the
-- old row stays, keeps its own amount and due date, and points at the new one.
-- A promise is never its own successor.
ALTER TABLE "payment_promise" ADD CONSTRAINT "payment_promise_reschedule_link_chk"
    CHECK (
        ("status" = 'RESCHEDULED') = ("rescheduled_to_promise_id" IS NOT NULL)
        AND "rescheduled_to_promise_id" IS DISTINCT FROM "id"
    );

-- --- a promise is born OPEN --------------------------------------------------
--
-- The same hole `enforce_financial_row_born_active` closes for money. A promise
-- inserted already FULFILLED would be a fulfilment nobody performed, against a
-- payment no transition ever validated — the trigger below is the ONLY place the
-- fulfilment invariants are checked, and it runs on UPDATE. A row born terminal
-- would walk straight past it.
--
-- A separate function rather than the financial one because a promise's terminal
-- state is a four-valued enum, not the three void columns that one reads.
--
-- THE DUE DATE IS NOT CHECKED HERE, and that is the rule, not an omission: an
-- initial promise MAY be created with a past due date and reads immediately as
-- derived MISSED (DECISION_LOG, 2026-08-15 — A promise may be born late). A
-- promise made last week and entered today is a real fact. Only a RESCHEDULED
-- successor must be due today or later, and that is checked where the reschedule
-- happens, because only there is the row known to be a successor.
CREATE OR REPLACE FUNCTION "enforce_payment_promise_born_open"() RETURNS trigger
    LANGUAGE plpgsql AS $fn$
BEGIN
    IF NEW."status" <> 'OPEN' THEN
        RAISE EXCEPTION
            'payment promise % cannot be created as %; ending a promise is a later, separate statement',
            NEW."id", NEW."status"
            USING ERRCODE = 'restrict_violation';
    END IF;

    RETURN NEW;
END;
$fn$;

