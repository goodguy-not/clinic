-- --- identity immutability ---------------------------------------------------
--
-- Provenance does not change: `created_at` and `created_by_user_id` say who
-- entered this booking and when, and a row that can be re-attributed is not a
-- record. Moving an appointment, reassigning a therapist or a room, and
-- recording an outcome are all ordinary updates and are deliberately not listed.
--
-- On the participant, `appointment_id` and `child_id` are listed for the same
-- reason `child.family_id` is: moving a seat to another child or another booking
-- rewrites who was treated. A genuine reassignment is a designed, audited repair
-- operation, not a side effect of an edit.
--
-- Both raise restrict_violation (SQLSTATE 23001), the code
-- `raise_append_only_violation` uses, so every "the database refuses to rewrite
-- this" failure asserts on one code.
CREATE OR REPLACE FUNCTION "enforce_appointment_identity_immutability"() RETURNS trigger
    LANGUAGE plpgsql AS $fn$
BEGIN
    IF NEW."id"                 IS DISTINCT FROM OLD."id"
        OR NEW."created_at"         IS DISTINCT FROM OLD."created_at"
        OR NEW."created_by_user_id" IS DISTINCT FROM OLD."created_by_user_id"
    THEN
        RAISE EXCEPTION
            'appointment % provenance is immutable; id, created_at and created_by_user_id cannot change',
            OLD."id"
            USING ERRCODE = 'restrict_violation';
    END IF;

    RETURN NEW;
END;
$fn$;

CREATE TRIGGER "appointment_enforce_identity_immutability"
    BEFORE UPDATE ON "appointment"
    FOR EACH ROW EXECUTE FUNCTION "enforce_appointment_identity_immutability"();

CREATE OR REPLACE FUNCTION "enforce_appointment_participant_identity_immutability"() RETURNS trigger
    LANGUAGE plpgsql AS $fn$
BEGIN
    IF NEW."id"             IS DISTINCT FROM OLD."id"
        OR NEW."appointment_id" IS DISTINCT FROM OLD."appointment_id"
        OR NEW."child_id"       IS DISTINCT FROM OLD."child_id"
    THEN
        RAISE EXCEPTION
            'appointment participant % identity is immutable; appointment_id, child_id and id cannot change',
            OLD."id"
            USING ERRCODE = 'restrict_violation';
    END IF;

    RETURN NEW;
END;
$fn$;

CREATE TRIGGER "appointment_participant_enforce_identity_immutability"
    BEFORE UPDATE ON "appointment_participant"
    FOR EACH ROW EXECUTE FUNCTION "enforce_appointment_participant_identity_immutability"();

-- NOTE ON WHAT IS NOT CONSTRAINED HERE, deliberately:
--
--   * a child in two overlapping sessions — an advisory-locked recomputation in
--     the booking checkpoint, for the reason given above;
--   * "an individual appointment has exactly one participant" — a service
--     invariant, as "a family has at least one guardian" is. A unique index on
--     `appointment_id` would state it and would also collapse the two-level
--     model into a one-to-one relation;
--   * a room's service restriction, and booking outside a therapist's
--     availability — both are cross-table reads and belong to the checkpoints
--     that own them;
--   * any relationship between a seat's `attendance` and its booking's `status`
--     — they are two facts, and the order in which they are recorded is the
--     transition checkpoint's decision.
--
-- NOTE ON COMPLETENESS: as in all three earlier migrations, a table owner can
-- still run `ALTER TABLE ... DISABLE TRIGGER`. Closing that gap needs a runtime
-- database role that does not own these tables, and remains a production
-- hardening item.
