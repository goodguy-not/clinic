-- --- appointment: the window is one fact, not three -------------------------
--
-- `ends_at` is stored so the exclusion constraints can range over it, and this
-- CHECK is what stops it becoming a second fact that disagrees with the first.
-- It also makes `ends_at > starts_at` unnecessary to state: a positive duration
-- implies it.
--
-- `timestamptz + interval` is immutable, so this is a legal CHECK expression.
-- `make_interval(mins => ...)` is used rather than `n * interval '1 minute'`
-- because it cannot be read as anything else.

ALTER TABLE "appointment" ADD CONSTRAINT "appointment_duration_chk"
    CHECK ("duration_minutes" > 0 AND "duration_minutes" <= 480);

ALTER TABLE "appointment" ADD CONSTRAINT "appointment_window_chk"
    CHECK ("ends_at" = "starts_at" + make_interval(mins => "duration_minutes"));

ALTER TABLE "appointment" ADD CONSTRAINT "appointment_note_chk"
    CHECK (
        "note" IS NULL
        OR (
            "note" = btrim("note")
            AND btrim("note") <> ''
            AND length("note") <= 2000
        )
    );

-- --- appointment: one status, one outcome record -----------------------------
--
-- Two biconditionals rather than one combined constraint, so a failure names
-- which pairing was broken. Each says the same thing in both directions: the
-- status requires its timestamp, and the timestamp is impossible without its
-- status. A SCHEDULED row therefore cannot carry a cancellation, and a cancelled
-- one cannot lack a reason (PROJECT_SPEC.md 9: actor, time and reason stay
-- inspectable).
--
-- There is deliberately no no-show timestamp here. A no-show is one child's
-- outcome and lives on the seat as `attendance = 'NO_SHOW'`, constrained
-- separately, and neither fact is derived from the other.

ALTER TABLE "appointment" ADD CONSTRAINT "appointment_completed_consistency_chk"
    CHECK (("status" = 'COMPLETED') = ("completed_at" IS NOT NULL));

ALTER TABLE "appointment" ADD CONSTRAINT "appointment_cancellation_consistency_chk"
    CHECK (
        ("status" IN ('CANCELLED_BY_FAMILY', 'CANCELLED_BY_CLINIC')) = ("cancelled_at" IS NOT NULL)
        AND ("cancelled_at" IS NOT NULL) = ("cancellation_reason" IS NOT NULL)
        AND (
            "cancellation_reason" IS NULL
            OR (
                "cancellation_reason" = btrim("cancellation_reason")
                AND btrim("cancellation_reason") <> ''
                AND length("cancellation_reason") <= 500
            )
        )
    );

-- --- appointment_participant -------------------------------------------------
--
-- `PENDING` means nobody has entered an outcome, so it cannot carry the time one
-- was entered; `ATTENDED` and `NO_SHOW` must. This is the seat's own fact and
-- says nothing about the booking's status: a child may fail to arrive for a
-- session that otherwise took place.

ALTER TABLE "appointment_participant" ADD CONSTRAINT "appointment_participant_attendance_consistency_chk"
    CHECK (("attendance" <> 'PENDING') = ("attendance_recorded_at" IS NOT NULL));

-- --- appointment_series ------------------------------------------------------
--
-- A series states exactly one bound, and carries exactly the column that bound
-- needs. PROJECT_SPEC.md 6 offers a number of occurrences or a last date; an
-- unbounded series would generate occurrences forever, and one carrying both
-- could contradict itself.

ALTER TABLE "appointment_series" ADD CONSTRAINT "appointment_series_end_chk"
    CHECK (
        ("end_mode" = 'OCCURRENCE_COUNT' AND "occurrence_count" IS NOT NULL AND "ends_on" IS NULL)
        OR ("end_mode" = 'END_DATE' AND "ends_on" IS NOT NULL AND "occurrence_count" IS NULL)
    );

-- A loose upper bound, not a modelled limit: it exists so a mistyped run of
-- digits is refused at entry rather than discovered as two thousand rows.
ALTER TABLE "appointment_series" ADD CONSTRAINT "appointment_series_occurrence_count_chk"
    CHECK ("occurrence_count" IS NULL OR ("occurrence_count" > 0 AND "occurrence_count" <= 260));

ALTER TABLE "appointment_series" ADD CONSTRAINT "appointment_series_range_chk"
    CHECK ("ends_on" IS NULL OR "ends_on" >= "starts_on");

ALTER TABLE "appointment_series" ADD CONSTRAINT "appointment_series_interval_chk"
    CHECK ("interval_weeks" >= 1 AND "interval_weeks" <= 12);

-- --- therapist availability --------------------------------------------------
--
-- `weekday` IS THE CLINIC'S OWN NUMBERING: 0 IS SATURDAY, 6 is Friday. The
-- Iranian week begins on Saturday, and this column is the shared product
-- contract (`weekdaySchema` in `@clinic/contracts`), consumed identically by
-- every tier.
--
-- It is deliberately NOT PostgreSQL's `EXTRACT(DOW)`, which begins on Sunday.
-- Native numbering is TRANSLATED at the boundary that reads an instant and is
-- never stored or exposed:
--
--     (EXTRACT(DOW FROM ts AT TIME ZONE 'Asia/Tehran')::int + 1) % 7
--
-- Saturday is DOW 6 and maps to 0; Friday is DOW 5 and maps to 6. Storing the
-- native value instead would put a second numbering in the system, and the two
-- would eventually disagree in exactly one place nobody looks.
--
-- The times are wall-clock in the clinic's timezone, not instants: "Saturdays,
-- 09:00 to 13:00" does not move when a particular date does.
--
-- There is deliberately NO overlap constraint between two windows. Two
-- overlapping working windows describe the same availability twice, which is
-- redundant rather than incorrect, and whether to merge or refuse them is a
-- decision for the checkpoint that manages availability.

ALTER TABLE "therapist_availability" ADD CONSTRAINT "therapist_availability_weekday_chk"
    CHECK ("weekday" BETWEEN 0 AND 6);

ALTER TABLE "therapist_availability" ADD CONSTRAINT "therapist_availability_window_chk"
    CHECK ("end_time" > "start_time");

ALTER TABLE "therapist_availability" ADD CONSTRAINT "therapist_availability_effective_range_chk"
    CHECK ("effective_to" IS NULL OR "effective_to" >= "effective_from");

-- An exception either closes a day or adds a window to it, and carries exactly
-- what that choice requires. A closed day with times, or an extra window without
-- them, is a half-stated fact that a later check would have to guess about.
ALTER TABLE "therapist_availability_exception" ADD CONSTRAINT "therapist_availability_exception_window_chk"
    CHECK (
        ("is_available" = false AND "start_time" IS NULL AND "end_time" IS NULL)
        OR ("is_available" = true AND "start_time" IS NOT NULL AND "end_time" IS NOT NULL AND "end_time" > "start_time")
    );

ALTER TABLE "therapist_availability_exception" ADD CONSTRAINT "therapist_availability_exception_reason_chk"
    CHECK (
        "reason" IS NULL
        OR (
            "reason" = btrim("reason")
            AND btrim("reason") <> ''
            AND length("reason") <= 500
        )
    );

-- --- resource overlap prevention ---------------------------------------------
--
-- Two constraints, one per resource, because the receptionist has to be told
-- WHICH resource is busy to fix the booking without guessing: each maps to its
-- own error code.
--
-- `[)` bounds, so 10:00-11:00 and 11:00-12:00 do not conflict. Back-to-back
-- sessions are the normal shape of a clinic day, and a closed upper bound would
-- refuse every one of them.
--
-- Each is partial on the two statuses that hold the resource. SCHEDULED and
-- COMPLETED occupy the therapist and the room; both cancellations release them,
-- which is what makes the slot re-bookable. A child failing to arrive does not
-- appear here at all — that is the seat's attendance, and the room and the hour
-- were still consumed.
--
-- Enforcing this in the database rather than by reading before writing is what
-- makes it hold under concurrency: two simultaneous bookings cannot both pass,
-- whatever the application checked first. Requires `btree_gist`, created by the
-- Milestone 2 migration.
--
-- A CHILD'S OWN OVERLAP IS NOT HERE, and deliberately. The child is on
-- `appointment_participant` and the time is on `appointment`, so no single-row
-- constraint can compare them. It is recomputed in SQL under a
-- transaction-scoped advisory lock keyed on the child when a seat is written —
-- the mechanism DECISION_LOG 2026-08-09 approved for blocking duplicate rules —
-- and that belongs to the booking checkpoint, not to this one. Denormalising the
-- window onto the seat to make an exclusion constraint possible would be a
-- different architecture, not a smaller one.

ALTER TABLE "appointment" ADD CONSTRAINT "appointment_no_therapist_overlap_excl"
    EXCLUDE USING GIST (
        "therapist_id" WITH =,
        tstzrange("starts_at", "ends_at", '[)') WITH &&
    ) WHERE ("status" IN ('SCHEDULED', 'COMPLETED'));

ALTER TABLE "appointment" ADD CONSTRAINT "appointment_no_room_overlap_excl"
    EXCLUDE USING GIST (
        "room_id" WITH =,
        tstzrange("starts_at", "ends_at", '[)') WITH &&
    ) WHERE ("status" IN ('SCHEDULED', 'COMPLETED'));

