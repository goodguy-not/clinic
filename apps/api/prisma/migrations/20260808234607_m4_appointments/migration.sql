-- Milestone 4, checkpoint A1 — the appointment schema foundation.
--
-- Five tables. `appointment` is the shared resource booking: one therapist, one
-- room, one service, one time range. `appointment_participant` is a child's seat
-- in it. `appointment_series` carries a weekly recurrence.
-- `therapist_availability` and `therapist_availability_exception` carry
-- recurring working windows plus dated exceptions (PROJECT_SPEC.md 5).
--
-- STRUCTURE ONLY. This checkpoint builds the schema for all five and the
-- behaviour of none: no booking, no occurrence generation, no availability
-- check, no group-booking rule. The tables exist now so the checkpoints that add
-- those behaviours do not each open with a migration.
--
-- NO FINANCIAL COLUMN APPEARS ANYWHERE IN THIS MIGRATION. No tariff reference,
-- no price snapshot, no tariff source, no charge, no discount, no amount.
-- Pricing a session is Milestone 5's; the read-only tariff suggestion a booking
-- screen shows is a lookup in a later checkpoint of this milestone, not stored
-- state here.
--
-- TWO FACTS, NOT ONE. `appointment.status` is the booking's lifecycle and has
-- four values; `appointment_participant.attendance` is what one child did.
-- Neither is derived from the other. A NO-SHOW IS A SEAT'S OUTCOME, NOT A
-- BOOKING'S STATUS: the room was held and the therapist waited, so the fact that
-- somebody did not arrive belongs to the seat that was empty.
--
-- The section above the "HAND-WRITTEN" banner is generated by Prisma.
-- Everything below it is reviewed by a human, because Prisma cannot express
-- CHECK constraints, exclusion constraints or triggers. Each hand-written object
-- is named, and `appointments-schema.int-spec.ts` asserts every name exists in
-- the PostgreSQL catalogue, so a future edit cannot quietly drop one.
--
-- THIS MIGRATION IS CREATE-ONLY. It adds three enums and five tables and alters
-- nothing that Milestones 1, 2 or 3 created, so it cannot fail on existing data
-- and there is nothing to back-fill. The `btree_gist` extension the two
-- exclusion constraints need was created by the Milestone 2 migration.
--
-- ON TIMESTAMPS: as in all three earlier migrations, `CURRENT_TIMESTAMP` is
-- PostgreSQL's exact synonym for `transaction_timestamp()`, left spelled as
-- Prisma generates it so drift detection cannot produce a false positive on a
-- synonym. `starts_at` is the one timestamp here that is not a clock reading: it
-- is a time somebody chose.

