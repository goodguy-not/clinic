-- Milestone 9.5, checkpoint A9 — SERVICE IMAGERY.
--
-- =====================================================================
-- WHAT THIS CHECKPOINT ADDS, AND WHAT IT DELIBERATELY DOES NOT
-- =====================================================================
--
-- A service was the last record in this product with a published page and no
-- way to put a photograph on it. This file closes that gap with the SIXTH real
-- foreign key under the existing A5 discriminator, and with nothing else: no
-- column on `service`, no new table, no new permission, no new error code and
-- no change to any rule the catalog already enforces.
--
-- `media_attachment.service_id` IS THE WHOLE OF THE STORAGE CHANGE.
-- `PUBLIC_SERVICE` therefore behaves like `THERAPIST_PROFILE`, `PUBLIC_ARTICLE`,
-- `PUBLIC_TESTIMONIAL`, `PUBLIC_SPACE` and `CLINIC_CONTENT_ENTRY` — it names a
-- row — and NOT like `CLINIC_SPACE` or `CLINIC_OPEN_GRAPH`, which name nothing.
-- The difference is the one that matters to a visitor: an owner row can be
-- withdrawn, and withdrawing it takes the photograph with it.
--
-- THE SERVICE GATE IS THREE CONDITIONS AND NOT ONE, and that is the single
-- design decision in this file. `is_public` is the intent to publish, `status =
-- 'ACTIVE'` is the service still being offered, and a non-null `public_slug` is
-- the address; the public projection has required all three since Milestone 9
-- checkpoint A1, and the media predicate now requires the same three. A service
-- that is deactivated keeps `is_public` — deactivation writes `status` alone —
-- so a predicate that read only the flag would take the page down and leave the
-- photograph anonymously servable to anybody holding the rendition id. One
-- service, one rule, in the projection and in the serving predicate alike.
--
-- EVERY A5 INVARIANT IS UNTOUCHED. No byte is stored in PostgreSQL, the master
-- is still not servable, EXIF is still stripped, attaching is still drafting,
-- publishing is still the manager's alone, unpublishing still revokes at the
-- origin on the very next request, and the five-minute window remains the only
-- cache promise this product makes.
--
-- NO CATALOG SEMANTICS MOVE. `service` gains no column. Nothing here touches a
-- tariff, a duration, a room restriction, an appointment or a charge, and no
-- operational fact becomes reachable from the public side: the projection gains
-- a photograph and the internal service id stays internal.
--
-- The section above the "HAND-WRITTEN" banner is generated by Prisma.
-- Everything below it is reviewed by a human. Each hand-written object is
-- named, and `service-imagery-schema.int-spec.ts` asserts every name exists in
-- the PostgreSQL catalogue, so a future edit cannot quietly drop one.

-- AlterTable
ALTER TABLE "media_attachment" ADD COLUMN     "service_id" UUID;

-- CreateIndex
CREATE INDEX "media_attachment_service_id_position_idx" ON "media_attachment"("service_id", "position");

-- AddForeignKey
ALTER TABLE "media_attachment" ADD CONSTRAINT "media_attachment_service_id_fkey" FOREIGN KEY ("service_id") REFERENCES "service"("id") ON DELETE RESTRICT ON UPDATE CASCADE;

-- ============================ HAND-WRITTEN ==================================

-- --- the attachment owner rule, restated over eight branches ----------------
--
-- REDEFINED RATHER THAN ADDED TO, for the reason checkpoints A7 and A8
-- redefined it: a polymorphic reference is only as good as the constraint that
-- pins it, and every branch has to name every column or a `PUBLIC_ARTICLE`
-- attachment could quietly also carry a `service_id` and two reads would
-- disagree about what it is attached to.
--
-- SIX BRANCHES NAME EXACTLY ONE ROW AND TWO NAME NOTHING. `CLINIC_SPACE` and
-- `CLINIC_OPEN_GRAPH` are the ownerless pair — the web tier's parking slot for
-- an uploaded but unplaced photograph, and the site's own social-preview
-- picture — and neither has a publication row to read.
ALTER TABLE "media_attachment" DROP CONSTRAINT "media_attachment_owner_chk";

ALTER TABLE "media_attachment" ADD CONSTRAINT "media_attachment_owner_chk"
    CHECK (
        CASE "owner_type"
            WHEN 'THERAPIST_PROFILE' THEN
                "therapist_id" IS NOT NULL AND "article_id" IS NULL
                AND "testimonial_id" IS NULL AND "space_id" IS NULL
                AND "content_entry_id" IS NULL AND "service_id" IS NULL
            WHEN 'PUBLIC_ARTICLE' THEN
                "article_id" IS NOT NULL AND "therapist_id" IS NULL
                AND "testimonial_id" IS NULL AND "space_id" IS NULL
                AND "content_entry_id" IS NULL AND "service_id" IS NULL
            WHEN 'PUBLIC_TESTIMONIAL' THEN
                "testimonial_id" IS NOT NULL AND "therapist_id" IS NULL
                AND "article_id" IS NULL AND "space_id" IS NULL
                AND "content_entry_id" IS NULL AND "service_id" IS NULL
            WHEN 'PUBLIC_SPACE' THEN
                "space_id" IS NOT NULL AND "therapist_id" IS NULL
                AND "article_id" IS NULL AND "testimonial_id" IS NULL
                AND "content_entry_id" IS NULL AND "service_id" IS NULL
            WHEN 'PUBLIC_SERVICE' THEN
                "service_id" IS NOT NULL AND "therapist_id" IS NULL
                AND "article_id" IS NULL AND "testimonial_id" IS NULL
                AND "space_id" IS NULL AND "content_entry_id" IS NULL
            WHEN 'CLINIC_CONTENT_ENTRY' THEN
                "content_entry_id" IS NOT NULL AND "therapist_id" IS NULL
                AND "article_id" IS NULL AND "testimonial_id" IS NULL
                AND "space_id" IS NULL AND "service_id" IS NULL
            WHEN 'CLINIC_SPACE' THEN
                "therapist_id" IS NULL AND "article_id" IS NULL
                AND "testimonial_id" IS NULL AND "space_id" IS NULL
                AND "content_entry_id" IS NULL AND "service_id" IS NULL
            WHEN 'CLINIC_OPEN_GRAPH' THEN
                "therapist_id" IS NULL AND "article_id" IS NULL
                AND "testimonial_id" IS NULL AND "space_id" IS NULL
                AND "content_entry_id" IS NULL AND "service_id" IS NULL
        END
    );
