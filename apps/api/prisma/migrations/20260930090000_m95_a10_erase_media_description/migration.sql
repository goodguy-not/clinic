-- Milestone 9.5, checkpoint A10 — A PHOTOGRAPH'S DESCRIPTION IS ERASED WITH IT.
--
-- Owner decision (DECISION_LOG, 2026-09-26, "a photograph's description is
-- erased with its bytes"): the alt text can name a child, so once a
-- photograph's bytes are erased its description goes too. What remains is the
-- row — a photograph existed, when, and where it was used — and the audit fact
-- that erasure happened (`media.bytes_erased`). `audit_log` never held the
-- words: `media.uploaded` and `media.alt_text_updated` record lengths.
--
-- DESTRUCTIVE FOR EXISTING ERASED ROWS. Any asset already erased under the A3
-- rules loses its description here, irreversibly and by design. Production has
-- not run A3's erasure yet, so in practice this touches only development
-- databases. A backup taken before this migration still holds those words until
-- it ages out of the backup retention; that is the ordinary backup loss window
-- in reverse, and no backup is rewritten.
--
-- The section above the "HAND-WRITTEN" banner is generated by Prisma.

-- AlterTable
ALTER TABLE "media_asset" ALTER COLUMN "alt_text" DROP NOT NULL;

-- ===========================================================================
-- HAND-WRITTEN: everything below this line is reviewed, not generated.
-- ===========================================================================

-- --- the erasure transition may now clear the description --------------------
--
-- A3's guard allowed exactly two columns to change when a photograph is erased:
-- the master key and the marker. The description is the third. Everything else
-- is as A3 wrote it — erasure only when due, final once done, no restore.

CREATE OR REPLACE FUNCTION "media_asset_erasure_guard"() RETURNS trigger
    LANGUAGE plpgsql
    SET search_path = pg_catalog, public
AS $$
BEGIN
    IF OLD."bytes_purged_at" IS NULL AND NEW."bytes_purged_at" IS NOT NULL THEN
        IF (to_jsonb(NEW) - 'master_storage_key' - 'bytes_purged_at' - 'alt_text')
           IS DISTINCT FROM (to_jsonb(OLD) - 'master_storage_key' - 'bytes_purged_at' - 'alt_text') THEN
            RAISE EXCEPTION 'media_asset % erasure may change nothing but its bytes and description', OLD."id"
                USING ERRCODE = '23001';
        END IF;

        IF NOT "media_asset_erasure_is_due"(OLD."id") THEN
            RAISE EXCEPTION 'media_asset % is not due for erasure', OLD."id"
                USING ERRCODE = '23001';
        END IF;
    ELSIF OLD."bytes_purged_at" IS NOT NULL THEN
        IF NEW."bytes_purged_at" IS DISTINCT FROM OLD."bytes_purged_at"
           OR NEW."master_storage_key" IS DISTINCT FROM OLD."master_storage_key" THEN
            RAISE EXCEPTION 'media_asset % has been erased, and erasure is final', OLD."id"
                USING ERRCODE = '23001';
        END IF;

        IF OLD."status" = 'ARCHIVED' AND NEW."status" = 'ACTIVE' THEN
            RAISE EXCEPTION 'media_asset % has been erased and cannot be restored', OLD."id"
                USING ERRCODE = '23001';
        END IF;
    END IF;

    RETURN NEW;
END;
$$;

-- --- the backfill: descriptions of photographs already erased ----------------
--
-- Passes the guard's "already erased" branch, which constrains only the marker,
-- the key and a restore.

UPDATE "media_asset" SET "alt_text" = NULL WHERE "bytes_purged_at" IS NOT NULL;

-- --- the description is present exactly while the bytes are ------------------
--
-- The `media_asset_purge_chk` equality, applied to the description: a row that
-- claims to be erased while still describing its photograph, a description
-- written back onto an erased photograph, and a live photograph with no
-- description are all impossible. `media_asset_alt_text_chk` still governs the
-- words whenever there are any (a CHECK on NULL passes).

ALTER TABLE "media_asset" ADD CONSTRAINT "media_asset_description_erasure_chk"
    CHECK (("alt_text" IS NULL) = ("bytes_purged_at" IS NOT NULL));
