-- Milestone 8, checkpoint C3 — the applied therapist share snapshot.
--
-- ONE TABLE, AND IT IS A HISTORICAL FACT RATHER THAN CONFIGURATION. C2 recorded
-- the AGREEMENT: what percentage a therapist takes, and between which dates.
-- This records what one session ACTUALLY EARNED, frozen at the instant somebody
-- rated it, and never re-resolved afterwards. The two concepts stay apart in
-- every direction: a rule may be voided, replaced or corrected after this row
-- exists and nothing here moves, because the percentage lives on this row as a
-- NUMBER and `applied_share_rule_id` is provenance only.
--
-- WHAT IS DELIBERATELY NOT HERE, and none of it is an oversight:
--
--   * NO `settlement_period` AND NO `settlement_line`. Closing a period is a
--     later checkpoint. `catalog-schema.int-spec.ts` lists every table in the
--     database, so one arriving early fails a test.
--   * NO UNRATED ROW, NO `unrated` FLAG AND NO ZERO PLACEHOLDER. A session
--     nobody has rated has NO ROW HERE. A placeholder would assert that
--     somebody earned nothing, which is a different claim from nobody having
--     decided yet, and the difference is a therapist's month. There is
--     therefore no DEFAULT on `applied_share_basis_points` either.
--   * NO NET FIGURE AND NO CONCESSION ALLOCATION. `therapist_gross_toman` and
--     `clinic_gross_toman` are the split of the PRE-DISCOUNT charge. Allocating
--     a concession between the two sides is the next accepted checkpoint, and
--     the temporary guard that refuses a therapist-borne portion is untouched.
--   * NO PAYOUT, NO LEDGER POSITION, NO BALANCE. This milestone records what
--     was earned, never money leaving the clinic.
--   * NO COLUMN ADDED TO `session_charge`. A rating points at a charge; a
--     charge knows nothing about settlement, and the immutability trigger that
--     protects it is untouched.
--
-- The section above the "HAND-WRITTEN" banner is generated by Prisma.
-- Everything below it is reviewed by a human, because Prisma cannot express
-- CHECK constraints, partial unique indexes or triggers. Each hand-written
-- object is named, and `settlement-rating-schema.int-spec.ts` asserts every name
-- exists in the PostgreSQL catalogue, so a future edit cannot quietly drop one.
--
-- THIS MIGRATION IS CREATE-ONLY. It adds one enum, one table, its indexes and
-- the objects below, plus ONE unique index on `session_charge` that no existing
-- row can violate (it is keyed on the primary key first). It alters no column,
-- drops nothing, and there is nothing to back-fill: every session charged before
-- this migration is UNRATED, which is exactly the state the absence of a row
-- means.

