-- ===========================================================================
-- HAND-WRITTEN: constraints and triggers Prisma cannot express.
--
-- NOTE ON THE COMPOSITE FOREIGN KEY ABOVE, WHICH IS THE UNUSUAL ONE AND IS THE
-- POINT OF THE WHOLE TABLE. A rating does not merely POINT AT a charge; it
-- copies five of its facts — the seat, the therapist, the clinic day and the
-- pre-discount amount — and a copy that can disagree with its source is worse
-- than no copy at all, because it is the copy a settlement statement reads.
-- Referencing all five through one key makes the disagreement UNREPRESENTABLE
-- rather than merely checked: there is no statement, from this service or from
-- a psql prompt, that can write a rating whose base amount is not the charge's
-- own. `session_charge` is immutable and is never deleted, so the key can never
-- be invalidated after the fact either.
--
-- It is the shape `session_charge_child_id_family_id_fkey` already uses to stop
-- a charge naming a child of another family, applied to the other side of the
-- money. `session_charge_settlement_snapshot_uq` exists only to give it a
-- target; it is keyed on the primary key first, so it can never refuse a row
-- the primary key would have accepted.
--
-- THERE IS DELIBERATELY NO SEPARATE `therapist_id` FOREIGN KEY. The composite
-- key above already reaches the therapist through the charge, which carries its
-- own `session_charge_therapist_id_fkey`; a second key would take a second lock
-- on `therapist` for a guarantee that already holds. The plain
-- `(therapist_id, service_date)` index remains, because a settlement statement
-- reads exactly that pair.
--
-- `applied_share_rule_id` IS RESTRICT AND NULLABLE, AND BOTH MATTER. RESTRICT
-- because provenance is history and history keeps its references — but the rule
-- may be VOIDED freely afterwards, which is an UPDATE and not a delete, and
-- nothing here re-reads it. Nullable because an EXPLICIT rating had no rule
-- behind it.
-- ===========================================================================

-- --- share percentage bounds -------------------------------------------------
--
-- The same bound as `therapist_share_rule_basis_points_chk`, restated here
-- rather than inherited, because an EXPLICIT rating is a percentage a manager
-- states directly and never passes through a rule.
ALTER TABLE "session_settlement" ADD CONSTRAINT "session_settlement_basis_points_chk"
    CHECK ("applied_share_basis_points" >= 0 AND "applied_share_basis_points" <= 10000);

-- --- the split identity ------------------------------------------------------
--
-- THE FROZEN ROUNDING RULE, WRITTEN AS A CONSTRAINT RATHER THAN TRUSTED TO THE
-- SERVICE. `therapist_gross = round_half_up(base * bp / 10000)` and the clinic
-- takes the exact residual, so the two halves sum to the pre-discount basis
-- with no tolerance and no reconciliation step (contracts `SHARE_ROUNDING`).
--
-- `(base * bp + 5000) / 10000` in BIGINT arithmetic IS half-up: PostgreSQL
-- integer division truncates toward zero, both operands are non-negative here
-- by the checks in this same constraint, and truncation of a non-negative
-- quotient is floor. No numeric, no float and no rounding mode of the day is
-- involved.
--
-- WHY THE DATABASE AND NOT ONLY `share-split.ts`. The service computes the same
-- expression in `BigInt`, and this refuses the row if the two ever disagree —
-- which is the only way a rounding change, a refactor or a repair script can
-- restate what was applied to a session that has already been settled. It is
-- the same division of labour as `enforce_charge_adjustment_bounds`: the
-- service produces the named refusal a person can act on, the database makes
-- the rule true of every writer.
ALTER TABLE "session_settlement" ADD CONSTRAINT "session_settlement_split_chk"
    CHECK (
        "base_amount_toman" >= 0
        AND "therapist_gross_toman" >= 0
        AND "clinic_gross_toman" >= 0
        AND "therapist_gross_toman" + "clinic_gross_toman" = "base_amount_toman"
        AND "therapist_gross_toman"
            = ("base_amount_toman" * "applied_share_basis_points" + 5000) / 10000
    );

-- --- provenance --------------------------------------------------------------
--
-- HOW THE PERCENTAGE WAS ARRIVED AT IS RECORDED, NOT INFERRED, and the two
-- shapes are mutually exclusive:
--
--   AUTOMATIC — resolved from an effective-dated share rule covering the
--   session's SERVICE DATE. The rule is named, and there is nothing to explain,
--   so `reason` is null.
--
--   EXPLICIT — a manager stated the percentage for this session. No rule stands
--   behind it, so `applied_share_rule_id` is null, and CLAUDE.md requires every
--   manual override to be reasoned, so `reason` is NOT null.
--
-- Enforced as one CHECK because the invariant is that the three columns move
-- together. An AUTOMATIC row carrying a reason would be an override recorded as
-- a routine application, which is precisely the confusion `rated_via` exists to
-- prevent.
ALTER TABLE "session_settlement" ADD CONSTRAINT "session_settlement_provenance_chk"
    CHECK (
        ("rated_via" = 'AUTOMATIC' AND "applied_share_rule_id" IS NOT NULL AND "reason" IS NULL)
        OR ("rated_via" = 'EXPLICIT' AND "applied_share_rule_id" IS NULL AND "reason" IS NOT NULL)
    );

-- --- reason shape ------------------------------------------------------------
ALTER TABLE "session_settlement" ADD CONSTRAINT "session_settlement_reason_chk"
    CHECK (
        "reason" IS NULL
        OR ("reason" = btrim("reason") AND btrim("reason") <> '' AND length("reason") <= 500)
    );

ALTER TABLE "session_settlement" ADD CONSTRAINT "session_settlement_void_reason_chk"
    CHECK (
        "void_reason" IS NULL
        OR (
            "void_reason" = btrim("void_reason")
            AND btrim("void_reason") <> ''
            AND length("void_reason") <= 500
        )
    );

-- --- void consistency --------------------------------------------------------
--
-- A withdrawn rating always records WHEN, BY WHOM and WHY, and a standing one
-- never claims any of the three.
ALTER TABLE "session_settlement" ADD CONSTRAINT "session_settlement_void_consistency_chk"
    CHECK (
        ("voided_at" IS NULL) = ("void_reason" IS NULL)
        AND ("voided_at" IS NULL) = ("voided_by_user_id" IS NULL)
    );

-- --- a rating never supersedes itself ----------------------------------------
ALTER TABLE "session_settlement" ADD CONSTRAINT "session_settlement_self_supersede_chk"
    CHECK (
        "supersedes_session_settlement_id" IS NULL
        OR "supersedes_session_settlement_id" <> "id"
    );

-- --- exactly one standing rating per session ---------------------------------
--
-- ONE VALID RATING PER SESSION CHARGE, for the reason
-- `session_charge_one_valid_per_participant_uq` gives one valid charge per
-- seat: a second standing rating is a therapist paid twice for one session, and
-- it is discovered by whoever reconciles the month rather than by whoever
-- created it.
--
-- PARTIAL ON `voided_at IS NULL`, which is what makes a correction expressible
-- at all: the withdrawn rating leaves the index and stays in the table, so the
-- replacement can be inserted in the SAME TRANSACTION as the withdrawal.
--
-- IT IS THE FINAL AUTHORITY UNDER CONCURRENCY. Every rating write takes the
-- parent charge row `FOR UPDATE` first and re-reads the standing rating under
-- it, so two simultaneous attempts serialise rather than race; this index is
-- what makes "exactly one" a property of the database instead of a property of
-- that discipline being remembered.
CREATE UNIQUE INDEX "session_settlement_one_valid_per_charge_uq"
    ON "session_settlement" ("session_charge_id") WHERE ("voided_at" IS NULL);

-- --- no-delete enforcement (reuses the Milestone 1 shared function) ----------
--
-- A settlement fact is a permanent financial record: withdrawal is `voided_at`,
-- never a DELETE (CLAUDE.md — final financial records are voided or adjusted,
-- never physically deleted). The TRUNCATE trigger is not optional; TRUNCATE
-- bypasses row-level triggers entirely.
CREATE TRIGGER "session_settlement_no_delete"
    BEFORE DELETE ON "session_settlement"
    FOR EACH ROW EXECUTE FUNCTION "raise_append_only_violation"();

CREATE TRIGGER "session_settlement_no_truncate"
    BEFORE TRUNCATE ON "session_settlement"
    FOR EACH STATEMENT EXECUTE FUNCTION "raise_append_only_violation"();

-- --- immutability ------------------------------------------------------------
--
-- WHAT A SESSION EARNED IS WRITTEN ONCE. Correcting a rating withdraws the row
-- and inserts a replacement naming it, so the figure that was applied and the
-- figure that replaced it are both readable, each with its own actor and
-- reason.
--
-- This is the trigger that makes the milestone's central promise structural
-- rather than procedural: a share rule changed, voided or replaced next month
-- cannot rewrite what was applied to last month's session, because there is no
-- statement that can rewrite this row at all. Exactly one transition is
-- permitted — standing to withdrawn — and everything else raises
-- restrict_violation (SQLSTATE 23001), the stable code every "the database
-- refuses to rewrite this" guard in this project uses.
CREATE OR REPLACE FUNCTION "enforce_session_settlement_immutability"() RETURNS trigger
    LANGUAGE plpgsql AS $fn$
BEGIN
    IF NEW."id"                                   IS DISTINCT FROM OLD."id"
        OR NEW."session_charge_id"                IS DISTINCT FROM OLD."session_charge_id"
        OR NEW."appointment_participant_id"       IS DISTINCT FROM OLD."appointment_participant_id"
        OR NEW."therapist_id"                     IS DISTINCT FROM OLD."therapist_id"
        OR NEW."service_date"                     IS DISTINCT FROM OLD."service_date"
        OR NEW."applied_share_basis_points"       IS DISTINCT FROM OLD."applied_share_basis_points"
        OR NEW."applied_share_rule_id"            IS DISTINCT FROM OLD."applied_share_rule_id"
        OR NEW."rated_via"                        IS DISTINCT FROM OLD."rated_via"
        OR NEW."base_amount_toman"                IS DISTINCT FROM OLD."base_amount_toman"
        OR NEW."therapist_gross_toman"            IS DISTINCT FROM OLD."therapist_gross_toman"
        OR NEW."clinic_gross_toman"               IS DISTINCT FROM OLD."clinic_gross_toman"
        OR NEW."reason"                           IS DISTINCT FROM OLD."reason"
        OR NEW."supersedes_session_settlement_id" IS DISTINCT FROM OLD."supersedes_session_settlement_id"
        OR NEW."created_at"                       IS DISTINCT FROM OLD."created_at"
        OR NEW."created_by_user_id"               IS DISTINCT FROM OLD."created_by_user_id"
    THEN
        RAISE EXCEPTION
            'session settlement % is immutable; only a single void transition is permitted',
            OLD."id"
            USING ERRCODE = 'restrict_violation';
    END IF;

    -- Withdrawal is a one-way door, and the withdrawal itself is history too:
    -- no unvoiding, and no revising the stated reason or the recorded actor
    -- afterwards.
    IF OLD."voided_at" IS NOT NULL
        AND (
            NEW."voided_at"            IS DISTINCT FROM OLD."voided_at"
            OR NEW."void_reason"       IS DISTINCT FROM OLD."void_reason"
            OR NEW."voided_by_user_id" IS DISTINCT FROM OLD."voided_by_user_id"
        )
    THEN
        RAISE EXCEPTION
            'session settlement % is already voided; the void cannot change again', OLD."id"
            USING ERRCODE = 'restrict_violation';
    END IF;

    RETURN NEW;
END;
$fn$;

CREATE TRIGGER "session_settlement_enforce_immutability"
    BEFORE UPDATE ON "session_settlement"
    FOR EACH ROW EXECUTE FUNCTION "enforce_session_settlement_immutability"();

