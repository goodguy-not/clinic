-- --- the attachment: THE OWNER RULE ----------------------------------------
--
-- Exactly the column matching `owner_type`, and neither of the other two.
-- `CLINIC_SPACE` names none of them, because there is no owner row to name.
--
-- Written as four explicit branches rather than a clever count, because this is
-- the constraint that makes three real foreign keys behave as one polymorphic
-- reference, and a reader has to be able to check it by eye.
ALTER TABLE "media_attachment" ADD CONSTRAINT "media_attachment_owner_chk"
    CHECK (
        CASE "owner_type"
            WHEN 'THERAPIST_PROFILE' THEN
                "therapist_id" IS NOT NULL AND "article_id" IS NULL AND "testimonial_id" IS NULL
            WHEN 'PUBLIC_ARTICLE' THEN
                "article_id" IS NOT NULL AND "therapist_id" IS NULL AND "testimonial_id" IS NULL
            WHEN 'PUBLIC_TESTIMONIAL' THEN
                "testimonial_id" IS NOT NULL AND "therapist_id" IS NULL AND "article_id" IS NULL
            WHEN 'CLINIC_SPACE' THEN
                "therapist_id" IS NULL AND "article_id" IS NULL AND "testimonial_id" IS NULL
        END
    );

-- PUBLICATION AND DETACHMENT ARE EACH ONE FACT WITH ONE ACTOR AND ONE INSTANT.
--
-- The third clause is the interesting one: A DETACHED ATTACHMENT MAY NOT BE
-- PUBLISHED. Taking a photograph off a page and leaving it marked published
-- would make the serving predicate's two conditions disagree about the same
-- row, and the application refuses the sequence outright
-- (`MEDIA_ATTACHMENT_PUBLISHED` — unpublish first, which is a manager act).
-- This states the resulting invariant where a hand-written UPDATE also has to
-- obey it.
ALTER TABLE "media_attachment" ADD CONSTRAINT "media_attachment_lifecycle_chk"
    CHECK (
        ("published_at" IS NULL) = ("published_by_user_id" IS NULL)
        AND ("detached_at" IS NULL) = ("detached_by_user_id" IS NULL)
        AND ("detached_at" IS NULL OR "published_at" IS NULL)
    );

ALTER TABLE "media_attachment" ADD CONSTRAINT "media_attachment_position_chk"
    CHECK ("position" BETWEEN 0 AND 999);

-- ONE STANDING ATTACHMENT OF ONE PHOTOGRAPH TO ONE OWNER.
--
-- Partial, on `detached_at IS NULL`, so the same photograph may be attached,
-- detached and attached again — which is an ordinary thing to do — while the
-- same photograph can never appear twice on one page at once. Two rows would
-- render the picture twice and would make unpublishing it ambiguous: one of
-- them would still be published.
--
-- Two indexes rather than one, because `CLINIC_SPACE` rows have NULL in all
-- three owner columns and NULLs do not collide in a unique index. The second
-- index is the clinic gallery's own version of the same rule.
CREATE UNIQUE INDEX "media_attachment_unique_live_owner_idx"
    ON "media_attachment" (
        "media_asset_id", "owner_type",
        coalesce("therapist_id", "article_id", "testimonial_id")
    )
    WHERE "detached_at" IS NULL AND "owner_type" <> 'CLINIC_SPACE';

CREATE UNIQUE INDEX "media_attachment_unique_live_clinic_space_idx"
    ON "media_attachment" ("media_asset_id")
    WHERE "detached_at" IS NULL AND "owner_type" = 'CLINIC_SPACE';

-- THE SERVING READ, AS AN INDEX.
--
-- Every anonymous request for a photograph runs the same `EXISTS`: is there a
-- standing, published attachment for this asset? This is that predicate,
-- narrowed to the rows that can satisfy it, so the busiest read on the public
-- site does not scan attachments that were detached or never published.
CREATE INDEX "media_attachment_live_idx"
    ON "media_attachment" ("media_asset_id", "owner_type")
    WHERE "detached_at" IS NULL AND "published_at" IS NOT NULL;

-- --- no deletion, on all three (reuses the Milestone 1 shared function) -----
--
-- A photograph is unpublished, detached or archived; it is never erased, and
-- the row that records where it used to be is how anybody afterwards can answer
-- a family asking when their child's photograph came off the site. The same
-- rule every catalog, content and financial table in this schema follows.
--
-- IT IS ALSO WHAT KEEPS THE RETENTION DECISION OPEN RATHER THAN PRE-EMPTED. A
-- routine that could DELETE from these tables would be a retention policy
-- implemented before anybody chose one.

