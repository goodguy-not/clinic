-- Milestone 9.5, checkpoint A5 — the media subsystem: the photograph a member
-- of staff uploads, the servable copies derived from it, and the single place
-- it has been put.
--
-- THREE TABLES AND THREE ENUMS, AND NOT ONE IMAGE BYTE IN POSTGRESQL. The
-- frozen owner decision for the pilot is that the API owns the bytes on
-- persistent disk; the columns below are KEYS into a directory NestJS owns.
-- Image data in a relational database bloats every dump, every backup and every
-- replica for no query anybody makes, and the alternative — object storage — is
-- a dependency, a credential and a second failure domain a single-site clinic
-- does not have yet.
--
-- THE UPLOADED FILE HAS NO COLUMN ANYWHERE HERE, AND THAT IS THE PRIVACY
-- DESIGN. `media_asset.source_content_type` and `source_byte_size` DESCRIBE what
-- arrived, because a colleague asking "did that upload work?" needs them; the
-- bytes themselves live in one process's memory for the length of one request
-- and are replaced by a re-encoded, re-oriented, METADATA-FREE master before
-- anything is written. An unedited telephone photograph carries the GPS
-- coordinate of wherever it was taken — a family's home, a colleague's home,
-- the clinic — and the narrowest way to obey a rule about a category of data is
-- not to hold the data. Nothing in this schema, and therefore nothing in any
-- backup of it, can be made to yield one.
--
-- THE ORIGINAL IS ALSO UNREACHABLE BY CONSTRUCTION AND NOT BY PREDICATE. The
-- master is a set of COLUMNS on `media_asset`; the servable copies are ROWS in
-- `media_rendition`; and the anonymous serving route selects from
-- `media_rendition` alone. There is no identifier a caller could send that names
-- the master, so "the original-quality file is not public" is enforced by there
-- being nothing to select rather than by a branch somebody could widen.
--
-- ORIENTATION IS APPLIED BEFORE METADATA IS DISCARDED. That order is enforced
-- in `image-processing.ts` rather than here, and it is stated in this banner
-- because reversing it produces a defect that looks like a feature: a
-- photograph lying on its side that no renderer can correct, because the field
-- that said to correct it is gone.
--
-- `media_attachment` IS THE TABLE THAT DECIDES WHAT THE WORLD SEES, AND IT
-- TAKES TWO DECISIONS BY TWO PEOPLE. `published_at` is a manager approving this
-- photograph in this place; the OWNER's own publication — `therapist.is_public`,
-- `public_article.is_public`, `public_testimonial.is_public` — is a decision
-- about the page. An anonymous request is served only when BOTH hold, which is
-- what lets a receptionist attach illustrations to a live article without
-- moving the live page, and what makes unpublishing the article take its
-- pictures down with it.
--
-- `CLINIC_SPACE` IS THE ONE OWNER WITH NO ROW, AND THE EXCEPTION IS HONEST.
-- `clinic_public_profile` is a single row that is always live, because editing
-- it IS publishing (Milestone 9, checkpoint A2). A clinic-space photograph is
-- therefore visible exactly while `published_at` is set, and the manager-only
-- authority over that column is the whole of the control.
--
-- THE OWNER IS A DISCRIMINATOR PLUS THREE REAL FOREIGN KEYS. The obvious
-- alternative — one nullable `owner_id` with no constraint — would make "which
-- pictures does this article have?" a query whose correctness depends on nobody
-- ever writing the wrong `owner_type`, and would let an attachment name an
-- article that does not exist. `media_attachment_owner_chk` requires exactly the
-- column matching `owner_type` and refuses the other two, so the polymorphism
-- is a labelling convenience over genuine referential integrity rather than a
-- replacement for it.
--
-- NOTHING HERE DELETES A BYTE, AND NO COLUMN SUGGESTS IT MIGHT. There is no
-- `deleted_at`, no purge marker and no retention clock. How long the clinic
-- keeps a photograph nobody publishes any more is a decision the owner has NOT
-- taken, and a schema that guessed either way — erasing on archive, or
-- promising to keep forever — would pre-empt it. All three tables carry the
-- Milestone 1 `no_delete` and `no_truncate` triggers, so when that decision
-- arrives it has to arrive as a reviewed migration.
--
-- WHAT IS DELIBERATELY NOT HERE: no folder, album, tag, collection or caption
-- table; no crop, focal point or art-direction column; no usage counter, view
-- count or analytics of any kind; no variant of any of this for documents,
-- clinical images or anything a family ever sent the clinic. This is
-- photographs for a public website, and nothing else.
--
-- The section above the "HAND-WRITTEN" banner is generated by Prisma.
-- Everything below it is reviewed by a human. Each hand-written object is
-- named, and `media-schema.int-spec.ts` asserts every name exists in the
-- PostgreSQL catalogue, so a future edit cannot quietly drop one.

