-- --- the asset -------------------------------------------------------------

-- The alt text a screen reader says instead of the photograph. Trimmed,
-- bounded, and free of markup — the last of the three is the load-bearing one,
-- for the A2 reason: staff-written text rendered to strangers is the exact
-- shape of a stored cross-site-scripting defect, and this product answers it by
-- refusing to STORE markup rather than by sanitising it on the way out.
--
-- REQUIRED, WITH NO EMPTY OPTION. An unlabelled image on a rehabilitation
-- clinic's public site is unreadable to exactly the visitors the clinic exists
-- to serve.
ALTER TABLE "media_asset" ADD CONSTRAINT "media_asset_alt_text_chk"
    CHECK (
        "alt_text" = btrim("alt_text")
        AND btrim("alt_text") <> ''
        AND length("alt_text") <= 200
        AND position('<' IN "alt_text") = 0
    );

-- THE ACCEPTED FORMAT LIST, IN THE DATABASE.
--
-- The uploader already decides this from the file's magic number and refuses
-- anything else, so this constraint can never fire on a row the application
-- writes. It is here because the list is a SECURITY decision rather than a
-- validation preference: `image/svg+xml` is absent because an SVG is a document
-- with a script engine attached, and serving one from the clinic's own origin
-- would put uploader-authored markup on the clinic's own domain. A constraint
-- makes that decision survive a future import, a data fix, or a second writer
-- nobody has written yet.
ALTER TABLE "media_asset" ADD CONSTRAINT "media_asset_source_content_type_chk"
    CHECK ("source_content_type" IN ('image/jpeg', 'image/png', 'image/webp'));

-- Sizes are positive, and the master's are bounded by the same ceiling the
-- encoder applies. A zero-byte or negative-width row is a bug that would
-- otherwise surface as a broken image on a live page with a `Content-Length`
-- that matches nothing.
ALTER TABLE "media_asset" ADD CONSTRAINT "media_asset_dimensions_chk"
    CHECK (
        "source_byte_size" > 0
        AND "master_byte_size" > 0
        AND "master_width" BETWEEN 1 AND 2560
        AND "master_height" BETWEEN 1 AND 2560
    );

-- SHA-256, lowercase hexadecimal, exactly 64 characters. Pinned so the value
-- served as an `ETag` cannot become something a cache would treat as a
-- different resource for reasons other than the bytes changing.
ALTER TABLE "media_asset" ADD CONSTRAINT "media_asset_master_content_hash_chk"
    CHECK ("master_content_hash" ~ '^[0-9a-f]{64}$');

-- A storage key is a RELATIVE path under one configured root, and it may not
-- climb out of it.
--
-- The application generates every key and resolves each one against the root
-- with an explicit containment check before it opens a file, so this constraint
-- is the second of two independent defences. It is worth having as a constraint
-- because the failure it prevents — a key edited into the database by hand, or
-- arriving through a future import, that makes the anonymous serving route hand
-- out a file from elsewhere on the disk — is a path traversal on the one route
-- in the product that reads a file.
ALTER TABLE "media_asset" ADD CONSTRAINT "media_asset_master_storage_key_chk"
    CHECK (
        "master_storage_key" ~ '^[a-z0-9][a-z0-9/._-]*$'
        AND position('..' IN "master_storage_key") = 0
        AND length("master_storage_key") <= 200
    );

-- ARCHIVING IS ONE FACT WITH ONE ACTOR AND ONE INSTANT, OR NONE OF THE THREE.
-- A row cannot be `ARCHIVED` without saying when and by whom, and cannot carry
-- either while it is `ACTIVE` — so restoring genuinely clears the claim rather
-- than leaving a stale one for somebody to read as current.
ALTER TABLE "media_asset" ADD CONSTRAINT "media_asset_archive_chk"
    CHECK (
        ("status" = 'ARCHIVED') = ("archived_at" IS NOT NULL)
        AND ("archived_at" IS NULL) = ("archived_by_user_id" IS NULL)
    );

