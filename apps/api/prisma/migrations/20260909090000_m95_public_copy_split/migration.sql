-- Milestone 9.5, checkpoint A6 — the editorial split, on the two catalog
-- records that never had one.
--
-- WHAT THIS MIGRATION MAKES POSSIBLE, IN ONE SENTENCE: somebody at the front
-- desk can rewrite what the website says about a service or a colleague, and
-- the website goes on saying exactly what a manager last approved until a
-- manager approves the new wording.
--
-- FOUR COLUMNS AND ONE REDEFINED CHECK. That is the whole schema footprint.
-- There is no draft table, no revision table, no editorial workflow table, no
-- review or approval queue, no scheduling column and no second copy of anything
-- that could disagree with the record it describes. The accepted A2 shape is
-- reused unchanged: TWO COLUMN SETS ON ONE ROW, exactly one previous state, and
-- that state is the one currently on the website.
--
-- WHY THE SPLIT IS THE ONLY HONEST SHAPE HERE. With one set of columns the
-- product has to choose between two broken rules — either a receptionist's
-- unreviewed sentence appears on the live page the instant they save it, or a
-- published description cannot be corrected without a manager doing the typing.
-- The accepted rule is neither (DECISION_LOG, 2026-09-08 — Editorial authority
-- and operational authority are split), and one row of copy cannot represent a
-- live version and a pending version at the same time.
--
-- `service.published_public_description` IS WHAT THE WEBSITE SAYS.
-- `service.public_description` becomes the WORKING DRAFT — the same column,
-- with a narrower meaning — so no existing writer changes shape and no data
-- moves. The public projection now selects the new column.
--
-- THE SERVICE NAME IS DELIBERATELY NOT DUPLICATED. A1 refused a published copy
-- of a service precisely because its name IS its public name: a second stored
-- version could let the site advertise something the clinic had stopped
-- offering. Renaming therefore still changes the public page at once, under
-- `service.update`, and no drafting authority reaches it. Only the description
-- — prose about the service rather than a fact about the catalogue — is split.
--
-- THE THERAPIST GETS THREE COLUMNS AND NOT FIVE. `published_public_display_
-- name`, `published_public_title` and `published_public_bio` are the copy.
-- `public_slug` is not duplicated, for the reason an article's is not: it is
-- immutable from the first publication, so the two copies could never differ on
-- a published row. `public_photo_path` IS NOT DUPLICATED EITHER, AND THAT IS A
-- ROLLOUT DECISION RATHER THAN AN OVERSIGHT — it is the pre-media legacy path
-- that the currently accepted public site still reads, it is scheduled for
-- removal by the Web checkpoint that finishes the A5 migration, and splitting a
-- column in order to delete it shortly afterwards would leave a backfill and a
-- constraint behind for nothing. It stays manager-only and no editorial
-- authority can write it.
--
-- `therapist_public_profile_chk` IS REDEFINED ONTO THE PUBLISHED NAME, and that
-- move is the opt-in surviving the split. Before, the rule was "a public
-- therapist has an approved display name"; the draft is now not that name, so
-- the rule would have been checking the wrong column and a manager could have
-- published somebody whose live page had no name on it. Refusing a publication
-- that has nothing to publish is the same rule as before, read against the
-- column that is actually published. It has a visible consequence: clearing the
-- DRAFT name of a published colleague is now accepted, because it changes no
-- live page, and the refusal moves to the publication that would make it real.
--
-- THE BACKFILL IS WHAT KEEPS THE LIVE SITE STILL. Every row that is public
-- today has its current copy written into the new published columns in this
-- transaction, so the first request after the migration returns exactly what
-- the last request before it did. Rows that are not public get NULL, which is
-- the truth: nothing about them has ever been published.
--
-- NO PROSE COLUMN GAINS A RULE ITS DRAFT DOES NOT HAVE. Each published column
-- carries the same trimmed, bounded CHECK as the column it is copied from — not
-- a stricter one, because a backfill cannot be refused by a rule the existing
-- data was never held to. The no-markup rule the A2 columns carry is stated on
-- the editorial REQUEST contract instead, where it governs new writing without
-- making old rows unwritable.
--
-- The section above the "HAND-WRITTEN" banner is generated by Prisma.
-- Everything below it is reviewed by a human. Each hand-written object is
-- named, and `public-copy-schema.int-spec.ts` asserts every name exists in the
-- PostgreSQL catalogue, so a future edit cannot quietly drop one.

-- AlterTable
ALTER TABLE "service" ADD COLUMN     "published_public_description" TEXT;

-- AlterTable
ALTER TABLE "therapist" ADD COLUMN     "published_public_bio" TEXT,
ADD COLUMN     "published_public_display_name" TEXT,
ADD COLUMN     "published_public_title" TEXT;

-- ===========================================================================
-- HAND-WRITTEN: everything below this line is reviewed, not generated.
-- ===========================================================================

-- --- what the website already says, carried onto the published columns -------
--
-- REACHABILITY, NOT `status`. A service that is public and has an address has
-- had a real URL, whatever its status is today, and a retired service that is
-- reactivated later must come back with the description it went away with.

UPDATE "service"
SET "published_public_description" = "public_description"
WHERE "is_public" IS TRUE
  AND "public_slug" IS NOT NULL;

-- A therapist has no reachability question the flag does not already answer:
-- `therapist_public_profile_chk` has required an address and a name for every
-- public row since A1.
UPDATE "therapist"
SET "published_public_display_name" = "public_display_name",
    "published_public_title" = "public_title",
    "published_public_bio" = "public_bio"
WHERE "is_public" IS TRUE;

-- --- the published copy, held to the same rules as its draft -----------------

ALTER TABLE "service" ADD CONSTRAINT "service_published_public_description_chk"
    CHECK (
        "published_public_description" IS NULL
        OR (
            "published_public_description" = btrim("published_public_description")
            AND btrim("published_public_description") <> ''
            AND length("published_public_description") <= 2000
        )
    );

ALTER TABLE "therapist" ADD CONSTRAINT "therapist_published_public_display_name_chk"
    CHECK (
        "published_public_display_name" IS NULL
        OR (
            "published_public_display_name" = btrim("published_public_display_name")
            AND btrim("published_public_display_name") <> ''
            AND length("published_public_display_name") <= 120
        )
    );

ALTER TABLE "therapist" ADD CONSTRAINT "therapist_published_public_title_chk"
    CHECK (
        "published_public_title" IS NULL
        OR (
            "published_public_title" = btrim("published_public_title")
            AND btrim("published_public_title") <> ''
            AND length("published_public_title") <= 120
        )
    );

ALTER TABLE "therapist" ADD CONSTRAINT "therapist_published_public_bio_chk"
    CHECK (
        "published_public_bio" IS NULL
        OR (
            "published_public_bio" = btrim("published_public_bio")
            AND btrim("published_public_bio") <> ''
            AND length("published_public_bio") <= 4000
        )
    );

-- --- the opt-in, read against the column that is actually published ---------
--
-- Same rule as A1's, same name, one column different. A public therapist has an
-- address and a PUBLISHED name to appear under; the reverse is still not
-- required, so copy may be prepared for somebody who is still private, which is
-- what lets preparing and publishing stay two separately audited acts.

ALTER TABLE "therapist" DROP CONSTRAINT "therapist_public_profile_chk";

ALTER TABLE "therapist" ADD CONSTRAINT "therapist_public_profile_chk"
    CHECK (
        "is_public" IS FALSE
        OR (
            "public_slug" IS NOT NULL
            AND "published_public_display_name" IS NOT NULL
        )
    );
