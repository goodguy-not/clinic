-- HAND-WRITTEN — everything below this line is reviewed by a human, not
-- generated.
--
-- NOTE ON THE FOREIGN KEYS: they are generated above rather than written here,
-- for the reason recorded in DECISION_LOG 2026-08-06 — Prisma DOES see foreign
-- keys, unlike CHECK constraints, partial indexes and triggers, so a
-- hand-written one reads as permanent schema drift and fails CI on every run.
-- They are the load-bearing half of this migration's attribution integrity:
--
--   * `(child_id, family_id)` -> `child` proves the charged child belongs to the
--     charged family. The alternative — storing only `child_id` and reading the
--     family through it — would make every family-level total a join away from a
--     row that names no family, and PROJECT_SPEC.md 7 requires a charge to record
--     both;
--   * `(appointment_participant_id, appointment_id)` -> `appointment_participant`
--     proves the charged seat belongs to the charged appointment. It is also what
--     keeps `appointment_id` traceable: the seat carries its own key to
--     `appointment`, so a charge can never name a booking that does not exist.
--     `appointment_id` therefore needs no second, single-column key of its own,
--     which would be a weaker restatement of one already held;
--   * `service_id` -> `service`, `therapist_id` -> `therapist`, and
--     `(service_id, duration_minutes)` -> `service_duration` prove the snapshot
--     names real catalog records and a session length the service actually
--     offers. Exactly the three keys `tariff` carries, for exactly the reason it
--     carries them, and ON DELETE RESTRICT for the same one: a duration that was
--     ever charged stays a valid historical reference;
--   * `tariff_id` -> `tariff` records WHICH price was applied, and deliberately
--     does not constrain `amount_toman` to still equal it. Tariffs are corrected
--     by void-and-replace (DECISION_LOG, 2026-08-06) and a charge must keep
--     reading as it was raised.
--
-- WHY THE SNAPSHOT IS KEYED TO THE CATALOG AND NOT TO THE PLACEMENT. An earlier
-- draft of this migration keyed
-- `(appointment_id, service_id, duration_minutes, therapist_id)` to `appointment`
-- ON UPDATE RESTRICT, reasoning that it made the snapshot and the booking
-- provably one session. It made them one session permanently, which is a
-- different and wrong thing. The accepted Milestone 4 lifecycle allows a
-- completed appointment to be reopened after its charge is voided, and a reopened
-- SCHEDULED booking to be moved to another therapist or another length; the
-- placement key would have refused that move for the lifetime of a charge that
-- had already been withdrawn. Financial history must record what happened and
-- must not veto what happens next. The catalog records it points at instead are
-- permanent and deactivate-only, so the same integrity is available without the
-- coupling.
--
-- THE ONE SNAPSHOT POSTGRESQL CANNOT PIN is `service_date`. It is
-- `clinic_date(appointment.starts_at)` — the clinic calendar day in Asia/Tehran
-- — and `clinic_date` is STABLE rather than IMMUTABLE, deliberately, because
-- timezone definitions can change (Milestone 3). A STABLE function may not
-- appear in a CHECK or a generated column, so the charge-posting service —
-- checkpoint A3 — computes it in SQL from the appointment it is charging. That
-- is stated here rather than left to be discovered.
--
-- NOTE ON DELETE BEHAVIOUR: every relation is ON DELETE RESTRICT and both tables
-- are protected outright below. Financial rows are never physically deleted
-- (PROJECT_SPEC.md 7); a mistake is voided, and both rows survive.
--
-- NOTE ON LOCK ORDER. Milestone 4 fixed the global order as
--
--     appointment -> service -> therapist -> room -> family -> child
--                 -> advisory keys
--
-- and the financial tables extend it at the end, before the advisory keys:
--
--     ... -> family -> child -> session_charge -> charge_adjustment
--                             -> advisory keys
--
-- A parent charge is therefore always locked BEFORE any adjustment against it is
-- written, which is exactly what `enforce_charge_adjustment_bounds` does, and no
-- path takes them the other way round. Nothing here takes an advisory lock: the
-- exactly-once guarantee is an index and the cumulative bound is a row lock, so
-- neither needs one.
-- ===========================================================================

-- --- session_charge: money, and what mode produced it ------------------------
--
-- The same 1,000,000,000-toman ceiling `tariff_price_bounds_chk` uses, and for
-- the same reason: a fat-finger guard, not a modelled maximum. Integer toman in
-- BIGINT throughout (DECISION_LOG, 2026-08-02 — Money unit). There is no signed
-- money here — a charge is what is owed, never a negative one, and a reversal is
-- a void.

ALTER TABLE "session_charge" ADD CONSTRAINT "session_charge_amount_bounds_chk"
    CHECK ("amount_toman" >= 0 AND "amount_toman" <= 1000000000);

-- FREE IS NOT "PAID, DISCOUNTED TO ZERO", and this is the constraint that keeps
-- the two apart in the ledger exactly as `tariff_price_mode_chk` keeps them
-- apart in the catalogue. A FREE charge came from a genuinely complimentary
-- programme and is zero; a PAID charge came from a real price and is positive,
-- and a family relieved of all of it keeps a PAID charge with an adjustment
-- against it. Both facts stay readable, and neither shape can be reached by
-- accident from the other.
--
-- A FREE charge is also, in consequence, unadjustable: an adjustment must be
-- positive and may not take a charge below zero, so nothing can be taken off a
-- charge of zero. That is the correct reading — there is no concession to record
-- on a session that was never priced.
ALTER TABLE "session_charge" ADD CONSTRAINT "session_charge_price_mode_chk"
    CHECK (
        ("price_mode" = 'PAID' AND "amount_toman" > 0)
        OR
        ("price_mode" = 'FREE' AND "amount_toman" = 0)
    );

-- Mirrors `appointment_duration_chk` and `service_duration_positive_chk`. The
