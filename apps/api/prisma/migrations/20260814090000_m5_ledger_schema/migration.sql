-- --- the effective-charge floor, and the lock that makes it hold -------------
--
-- "The family's effective session charge must never be negative" (CLAUDE.md) is
-- a statement about a SUM, not about a row, so no CHECK can express it: a CHECK
-- sees one row and the rule spans every active adjustment against one charge.
--
-- Reading the sum and then inserting would be correct in a single-threaded
-- world and wrong in this one — two adjustments of 60,000 against a charge of
-- 100,000, submitted together, would both read a stale total of zero and both
-- pass, leaving the family owing minus twenty thousand toman. THE PARENT ROW IS
-- THEREFORE LOCKED FIRST. `FOR UPDATE` on `session_charge` serialises every
-- adjustment against one charge: the second waits for the first to commit and
-- then re-reads a total that includes it.
--
-- The same lock decides the other race. Voiding a charge is an UPDATE on the same
-- row, so an adjustment and a void cannot interleave: whichever commits first,
-- the other sees the committed state and either refuses or proceeds correctly.
--
-- This is in the database rather than in the Milestone 5 service because it must
-- hold for the service that does not exist yet, for the repair script written at
-- 2 a.m., and for the psql session — the same standard `enforce_tariff_immutability`
-- set for prices.
--
-- Only INSERT is guarded. The only permitted UPDATE is a void, which removes an
-- adjustment from the active sum and so can never break the floor.
CREATE OR REPLACE FUNCTION "enforce_charge_adjustment_bounds"() RETURNS trigger
    LANGUAGE plpgsql AS $fn$
DECLARE
    charge_amount bigint;
    charge_voided timestamptz;
    active_total  bigint;
BEGIN
    -- The parent, locked before anything is decided. Taken here in a BEFORE
    -- trigger, which runs ahead of the foreign key's own check on the same row,
    -- so the stronger lock is always the first one acquired.
    SELECT "amount_toman", "voided_at"
      INTO charge_amount, charge_voided
      FROM "session_charge"
     WHERE "id" = NEW."session_charge_id"
       FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'session charge % does not exist', NEW."session_charge_id"
            USING ERRCODE = 'foreign_key_violation';
    END IF;

    -- A voided charge is history. Adding a concession to it would change what a
    -- withdrawn record says, and the replacement charge — not this one — is what
    -- a live adjustment belongs to.
    IF charge_voided IS NOT NULL THEN
        RAISE EXCEPTION
            'session charge % is voided and cannot be adjusted', NEW."session_charge_id"
            USING ERRCODE = 'restrict_violation';
    END IF;

    SELECT coalesce(sum("amount_toman"), 0)
      INTO active_total
      FROM "charge_adjustment"
     WHERE "session_charge_id" = NEW."session_charge_id"
       AND "voided_at" IS NULL;

    IF active_total + NEW."amount_toman" > charge_amount THEN
        RAISE EXCEPTION
            'adjustments against session charge % would total %, exceeding the charge of %',
            NEW."session_charge_id", active_total + NEW."amount_toman", charge_amount
            USING ERRCODE = 'check_violation';
    END IF;

    RETURN NEW;
END;
$fn$;

CREATE TRIGGER "charge_adjustment_enforce_bounds"
    BEFORE INSERT ON "charge_adjustment"
    FOR EACH ROW EXECUTE FUNCTION "enforce_charge_adjustment_bounds"();

