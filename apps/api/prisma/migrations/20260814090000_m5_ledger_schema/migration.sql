-- Milestone 5, checkpoint A1 — the ledger schema and financial integrity
-- foundation.
--
-- TWO TABLES. `session_charge` is what one completed, attended seat costs one
-- family; `charge_adjustment` is an append-only reduction of one such charge.
--
-- STRUCTURE ONLY. This checkpoint builds the schema for both and the behaviour
-- of neither: there is no charge-posting service, no re-post endpoint, no
-- ledger permission, no error vocabulary and no family-account read. The tables
-- exist now so the checkpoints that add those behaviours do not each open with
-- a migration, and so the financial spine is settled before any money exists.
--
-- NO FINANCIAL COLUMN IS ADDED TO `appointment` OR `appointment_participant`.
-- The Milestone 4 boundary holds exactly as it was written: the tariff stays a
-- read-only suggestion at booking time (DECISION_LOG, 2026-08-13) and becomes a
-- stored amount only here, at the completion that creates money. THE CHARGE ROW
-- IS THE FINANCIAL SNAPSHOT. The two unique indexes this migration adds to
-- Milestone 3 and 4 tables assert no new uniqueness — each is unique on a
-- superset of a primary key that is unique already — and exist solely as
-- targets the composite foreign keys below can reference.
--
-- A CHARGE POINTS AT CATALOG RECORDS, NEVER AT A PLACEMENT. The snapshotted
-- service, therapist and session length are keyed to `service`, `therapist` and
-- `service_duration` — permanent, deactivate-only records — and NOT to the
-- appointment's current therapist, service and duration. Keying them to the
-- placement would mean a voided historical charge pinned its appointment
-- forever: a charge is voided, the completed appointment reopened, and the
-- reopened booking is then legitimately movable to another therapist or another
-- length, which is the Milestone 4 lifecycle working exactly as approved. The
-- old charge must keep saying what the session it represented was, without
-- being able to veto what the booking becomes next.
--
-- NOTHING HERE IS A PAYMENT. No payment, credit, allocation, promise, balance,
-- therapist share, settlement percentage or settlement period. Those are
-- Milestones 6 and 8.
--
-- The section above the "HAND-WRITTEN" banner is generated by Prisma.
-- Everything below it is reviewed by a human, because Prisma cannot express
-- CHECK constraints, partial indexes or triggers. Each hand-written object is
-- named, and `ledger-schema.int-spec.ts` asserts every name exists in the
-- PostgreSQL catalogue, so a future edit cannot quietly drop one.
--
-- THIS MIGRATION IS CREATE-ONLY. It adds two tables, two unique indexes and
-- the objects below; it alters no existing column and drops nothing, so it
-- cannot fail on existing data and there is nothing to back-fill. Both unique
-- indexes are built over columns led by a primary key, so no existing row can
-- violate one.
--
-- ON TIMESTAMPS: as in all four earlier migrations, `CURRENT_TIMESTAMP` is
-- PostgreSQL's exact synonym for `transaction_timestamp()`, left spelled as
-- Prisma generates it so drift detection cannot produce a false positive on a
-- synonym. `service_date` is the one date here that is not a clock reading: it
-- is `clinic_date(appointment.starts_at)`, the clinic calendar day the session
-- happened on.

