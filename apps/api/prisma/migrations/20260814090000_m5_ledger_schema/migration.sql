-- --- financial immutability ---------------------------------------------------
--
-- The same model `enforce_tariff_immutability` established, applied to the rows
-- that are money rather than to the rows that price it. Everything a charge says
-- about who was treated, by whom, for what, on which day and for how much is
-- written once. EXACTLY ONE TRANSITION IS PERMITTED: active to voided.
--
-- Correcting a charge is therefore void-and-re-post, not an edit, and both rows
-- survive — which is what makes "what did this family owe in Mordad?" a question
-- later corrections cannot change the answer to.
--
-- Unvoiding, and revising a void reason or actor after the fact, are refused with
-- the same `restrict_violation` (SQLSTATE 23001) the shared no-delete function
-- raises, so every "the database refuses to rewrite this" failure asserts on one
-- code.
CREATE OR REPLACE FUNCTION "enforce_session_charge_immutability"() RETURNS trigger
    LANGUAGE plpgsql AS $fn$
BEGIN
    IF NEW."id"                         IS DISTINCT FROM OLD."id"
        OR NEW."family_id"                  IS DISTINCT FROM OLD."family_id"
        OR NEW."child_id"                   IS DISTINCT FROM OLD."child_id"
        OR NEW."appointment_id"             IS DISTINCT FROM OLD."appointment_id"
        OR NEW."appointment_participant_id" IS DISTINCT FROM OLD."appointment_participant_id"
        OR NEW."service_id"                 IS DISTINCT FROM OLD."service_id"
        OR NEW."therapist_id"               IS DISTINCT FROM OLD."therapist_id"
        OR NEW."duration_minutes"           IS DISTINCT FROM OLD."duration_minutes"
        OR NEW."service_date"               IS DISTINCT FROM OLD."service_date"
        OR NEW."tariff_id"                  IS DISTINCT FROM OLD."tariff_id"
        OR NEW."price_mode"                 IS DISTINCT FROM OLD."price_mode"
        OR NEW."amount_toman"               IS DISTINCT FROM OLD."amount_toman"
        OR NEW."created_at"                 IS DISTINCT FROM OLD."created_at"
        OR NEW."created_by_user_id"         IS DISTINCT FROM OLD."created_by_user_id"
    THEN
        RAISE EXCEPTION
            'session charge % is immutable; only a single void transition is permitted', OLD."id"
            USING ERRCODE = 'restrict_violation';
    END IF;

    IF OLD."voided_at" IS NOT NULL
        AND (
            NEW."voided_at"          IS DISTINCT FROM OLD."voided_at"
            OR NEW."voided_by_user_id" IS DISTINCT FROM OLD."voided_by_user_id"
            OR NEW."void_reason"       IS DISTINCT FROM OLD."void_reason"
        )
    THEN
        RAISE EXCEPTION
            'session charge % is already voided; the void cannot be changed or reversed', OLD."id"
            USING ERRCODE = 'restrict_violation';
    END IF;

    RETURN NEW;
END;
$fn$;

CREATE TRIGGER "session_charge_enforce_immutability"
    BEFORE UPDATE ON "session_charge"
    FOR EACH ROW EXECUTE FUNCTION "enforce_session_charge_immutability"();

-- The same shape for the adjustment. The allocation is as defining as the amount:
-- a clinic-borne concession quietly becoming a therapist-borne one would move a
-- cost onto somebody who never agreed to it, which is the whole class of edit
-- this trigger exists to refuse.
CREATE OR REPLACE FUNCTION "enforce_charge_adjustment_immutability"() RETURNS trigger
    LANGUAGE plpgsql AS $fn$
BEGIN
    IF NEW."id"                          IS DISTINCT FROM OLD."id"
        OR NEW."session_charge_id"           IS DISTINCT FROM OLD."session_charge_id"
        OR NEW."amount_toman"                IS DISTINCT FROM OLD."amount_toman"
        OR NEW."therapist_discount_toman"    IS DISTINCT FROM OLD."therapist_discount_toman"
        OR NEW."clinic_discount_toman"       IS DISTINCT FROM OLD."clinic_discount_toman"
        OR NEW."reason"                      IS DISTINCT FROM OLD."reason"
        OR NEW."created_at"                  IS DISTINCT FROM OLD."created_at"
        OR NEW."created_by_user_id"          IS DISTINCT FROM OLD."created_by_user_id"
    THEN
        RAISE EXCEPTION
            'charge adjustment % is immutable; only a single void transition is permitted', OLD."id"
            USING ERRCODE = 'restrict_violation';
    END IF;

    IF OLD."voided_at" IS NOT NULL
        AND (
            NEW."voided_at"          IS DISTINCT FROM OLD."voided_at"
            OR NEW."voided_by_user_id" IS DISTINCT FROM OLD."voided_by_user_id"
            OR NEW."void_reason"       IS DISTINCT FROM OLD."void_reason"
        )
    THEN
        RAISE EXCEPTION
            'charge adjustment % is already voided; the void cannot be changed or reversed', OLD."id"
            USING ERRCODE = 'restrict_violation';
    END IF;

    RETURN NEW;
END;
$fn$;

CREATE TRIGGER "charge_adjustment_enforce_immutability"
    BEFORE UPDATE ON "charge_adjustment"
    FOR EACH ROW EXECUTE FUNCTION "enforce_charge_adjustment_immutability"();

-- NOTE ON WHAT IS NOT CONSTRAINED HERE, deliberately:
--
--   * "only an attended participant in a completed appointment may create a
--     primary session charge" — the attendance and the status live on two other
--     tables and both are legitimately recorded after the fact, so a CHECK cannot
--     see them and a trigger reading them would freeze the seat against later
--     correction. It is enforced where charges are posted, which is checkpoint A3;
--   * the snapshot still matching the appointment's CURRENT service, therapist or
--     duration — deliberately not constrained, for the reason given above the
--     banner. A voided charge keeps its own facts and the live booking keeps
--     moving;
--   * `amount_toman` equalling the referenced tariff's price — a snapshot must
--     outlive the price it came from, and tariffs are corrected by
--     void-and-replace;
--   * `service_date` matching the appointment's own day — `clinic_date` is STABLE
--     and cannot appear in a CHECK, for the reason given above the banner;
--   * anything about payments, credits, balances or therapist shares — none of
--     those exist, and a constraint anticipating one would be a rule invented
--     before its milestone.
--
