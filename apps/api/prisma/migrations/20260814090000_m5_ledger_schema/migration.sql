-- --- exactly once, per seat --------------------------------------------------
--
-- "Each appointment participant has at most one valid primary session charge;
-- retries are idempotent" (CLAUDE.md; PROJECT_SPEC.md 6) is THIS INDEX. A second
-- posting for a seat that already has a live charge is refused by PostgreSQL,
-- not by a read-then-write the application performs — so two simultaneous
-- completions cannot both succeed, whatever either checked first, and no generic
-- idempotency table is needed to say it.
--
-- Partial on `voided_at IS NULL`, which is what keeps void-then-re-post
-- structurally possible: the voided row leaves the index and stops competing,
-- the replacement takes its place, and BOTH rows survive in the table. That is
-- how a corrected charge is made, and it is the only way one is.
--
-- A partial unique index is invisible to `prisma migrate diff`, exactly like
-- `child_national_id_uq` and `guardian_one_primary_per_family_uq` before it, so
-- it lives here and is pinned by name in the schema test.

CREATE UNIQUE INDEX "session_charge_one_valid_per_participant_uq"
    ON "session_charge" ("appointment_participant_id")
    WHERE ("voided_at" IS NULL);

