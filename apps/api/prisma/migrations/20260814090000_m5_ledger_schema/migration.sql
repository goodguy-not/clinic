-- THE MILESTONE 5 POLICY, and the reason this table can be trusted before
-- settlement exists: every discount recorded here is genuinely 100% clinic-borne.
--
-- Therapist settlement — effective-dated share percentages, their snapshot onto a
-- completed session, and a therapist's participation in a concession — is
-- Milestone 8 and is not approved here. Without it there is no basis on which a
-- therapist could be said to have agreed to bear part of a discount, and a row
-- claiming they had would be an unfunded liability recorded as a fact.
--
-- The honest alternative to this constraint is not "allow a non-zero therapist
-- share and sort it out later". It is to refuse the concession outright, which is
-- what this does: a shared or therapist-borne discount is NOT REPRESENTABLE in
-- Milestone 5 and cannot be disguised as a clinic-borne one. Together with the
-- split identity above, this forces `clinic_discount_toman = amount_toman`.
