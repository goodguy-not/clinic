-- --- a financial row is born live --------------------------------------------
--
-- A charge inserted already voided would be a row that never existed as money,
-- and — far worse — WOULD SIDESTEP THE EXACTLY-ONCE INDEX, which does not index
-- voided rows. A seat could then accumulate any number of born-dead charges, and
-- the guarantee that reads as a unique index would quietly not be one.
--
-- Voiding is a decision an actor makes about a record that exists, and it is
-- always a second statement.
CREATE OR REPLACE FUNCTION "enforce_financial_row_born_active"() RETURNS trigger
    LANGUAGE plpgsql AS $fn$
BEGIN
    IF NEW."voided_at" IS NOT NULL
        OR NEW."voided_by_user_id" IS NOT NULL
        OR NEW."void_reason" IS NOT NULL
    THEN
        RAISE EXCEPTION
            '% % cannot be created already voided; a void is a later, separate statement',
            TG_TABLE_NAME, NEW."id"
            USING ERRCODE = 'restrict_violation';
    END IF;

    RETURN NEW;
END;
$fn$;

CREATE TRIGGER "session_charge_enforce_born_active"
    BEFORE INSERT ON "session_charge"
    FOR EACH ROW EXECUTE FUNCTION "enforce_financial_row_born_active"();

