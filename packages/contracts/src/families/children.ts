import { z } from 'zod';
import { isoDateSchema } from '../dates';
import {
  childSexSchema,
  fileNumberSchema,
  legacyPaperFileNumberSchema,
  nationalIdSchema,
  noteSchema,
  noticeCodeSchema,
  personNameSchema,
  recordStatusSchema,
  referralSourceSchema,
} from './common';
import { childSummarySchema, familySchema } from './families';

/**
 * A child is the person treated, and the subject every session charge will name
 * (PROJECT_SPEC.md 5). The family holds the balance; this row identifies who
 * the session was for.
 *
 * Given and family name are separate fields rather than one. Two children in a
 * family sharing a given name and a birth date is a duplicate; two children in
 * different families sharing a given name is a coincidence, and telling those
 * apart needs the parts kept apart. It also lets the interface prefill a
 * sibling's surname, which is most of what "do not type it twice" means here.
 */
export const childSchema = z.strictObject({
  id: z.uuid(),
  familyId: z.uuid(),
  firstName: z.string(),
  lastName: z.string(),
  birthDate: isoDateSchema,
  /** Server-assigned from a sequence, and immutable once written. */
  fileNumber: fileNumberSchema,
  legacyPaperFileNumber: z.string().nullable(),
  nationalId: z.string().nullable(),
  sex: childSexSchema,
  referralSource: z.string().nullable(),
  note: z.string().nullable(),
  status: recordStatusSchema,
  deactivatedAt: z.iso.datetime().nullable(),
  createdAt: z.iso.datetime(),
});

export type Child = z.infer<typeof childSchema>;

/**
 * Registering a child.
 *
 * `fileNumber` is deliberately absent. It is generated by the server from a
 * sequence, so there is no field for staff to type, no collision for them to
 * resolve, and no way for two people registering at once to choose the same
 * number. An existing paper number goes in `legacyPaperFileNumber`, which is
 * separately unique — the two schemes coexist rather than competing for one
 * column.
 *
 * `birthDate` is required and Gregorian `YYYY-MM-DD`. The interface reads and
 * writes Jalali and converts at its own edge. A date after the clinic's own
 * calendar day in Asia/Tehran is refused by the service, not by a constraint:
 * "today" is not immutable, so PostgreSQL will not accept it in a CHECK.
 *
 * `nationalId` is optional. It is the strongest duplicate signal available, and
 * requiring it would refuse a newborn who does not have one yet.
 */
export const createChildRequestSchema = z.strictObject({
  firstName: personNameSchema,
  lastName: personNameSchema,
  birthDate: isoDateSchema,
  sex: childSexSchema,
  nationalId: nationalIdSchema.nullable(),
  legacyPaperFileNumber: legacyPaperFileNumberSchema.nullable(),
  referralSource: referralSourceSchema.nullable(),
  note: noteSchema.nullable(),
});

export type CreateChildRequest = z.infer<typeof createChildRequestSchema>;

/**
 * Editing a child.
 *
 * The same fields. `familyId` is not among them and never will be: moving a
 * child between families rewrites who owes for every session they have ever
 * had, and the database refuses the change outright. A genuine reassignment is
 * a designed, audited repair operation belonging to the milestone that owns
 * financial history.
 */
export const updateChildRequestSchema = createChildRequestSchema;

export type UpdateChildRequest = z.infer<typeof updateChildRequestSchema>;

export const childDetailResponseSchema = z.strictObject({
  child: childSchema,
  /** So an edit screen can show which family it belongs to without a second call. */
  family: familySchema,
  siblings: z.array(childSummarySchema),
});

export type ChildDetailResponse = z.infer<typeof childDetailResponseSchema>;

/** As with families, a successful write reports any non-blocking similarity. */
export const childWriteResponseSchema = childDetailResponseSchema.extend({
  nonBlockingWarnings: z.array(noticeCodeSchema),
});

export type ChildWriteResponse = z.infer<typeof childWriteResponseSchema>;
